        // 尝试挂钩 TMP 文本入口(base set_text 在本作会 IL 失败; SetText 方法多半可挂)。
        private void PatchTmp(Harmony harmony)
        {
            var pre = new HarmonyMethod(typeof(Plugin).GetMethod("Tmp_Prefix",
                BindingFlags.Static | BindingFlags.NonPublic));
            pre.priority = Priority.First;   // 让 LGTS 先于 AT 拿到原始整句 (P1-03)
            Type t = AccessTools.TypeByName("TMPro.TMP_Text");
            if (t == null) { Log.LogWarning("未找到 TMPro.TMP_Text"); D("未找到 TMP_Text"); return; }
            var setter = t.GetMethod("set_text", BindingFlags.Public | BindingFlags.Instance,
                null, new Type[] { typeof(string) }, null);
            if (setter != null) TryPatch(harmony, setter, pre, "TMP_Text.set_text");
            else D("TMP hook ABSENT: set_text 未找到");   // v1.3.7 (C7): 未找到也显式记录
            var setText = t.GetMethod("SetText", BindingFlags.Public | BindingFlags.Instance,
                null, new Type[] { typeof(string) }, null);
            if (setText != null) TryPatch(harmony, setText, pre, "TMP_Text.SetText(string)");
            else D("TMP hook ABSENT: SetText(string) 未找到(本 TMP 版本该重载多为 SetText(string,bool) 默认参形态, 会绕回已挂路径)");
            // 部分调用走 SetText(string, bool)
            var setText2 = t.GetMethod("SetText", BindingFlags.Public | BindingFlags.Instance,
                null, new Type[] { typeof(string), typeof(bool) }, null);
            if (setText2 != null) TryPatch(harmony, setText2, pre, "TMP_Text.SetText(string,bool)");
            else D("TMP hook ABSENT: SetText(string,bool) 未找到");
        }
        private void TryPatch(Harmony harmony, MethodInfo m, HarmonyMethod pre, string label)
        {
            try { harmony.Patch(m, prefix: pre); Log.LogInfo("已挂钩 " + label); D("TMP hook OK: " + label); }
            catch (Exception e) { Log.LogWarning("挂钩 " + label + " 失败: " + e.Message); D("TMP hook FAIL: " + label + " : " + e.Message); }
        }

        // TMP 渲染层前置: __0 = 即将显示的文本; __instance = TMP 组件(取路径供诊断)。
        // v1.3.10: 热钩子顶层 try/catch 纵深防御 —— 钩内任何异常不得中断游戏写入流程(P2-3)。
        private static int HookErr;
        private static void Tmp_Prefix(ref string __0, object __instance)
        {
            try { Tmp_PrefixCore(ref __0, __instance); }
            catch (Exception e) { if (HookErr < 20) { HookErr++; D("[HOOK ERR] TMP: " + e.Message); } }
        }
        private static void Tmp_PrefixCore(ref string __0, object __instance)
        {
            if (Runner == null) EnsureRunner();   // 宿主被销毁则借热路径重建 (v1.3.5)
            string s = __0;
            if (string.IsNullOrEmpty(s)) return;
            TmpSeen++;
            if (TmpSeen % 500 == 0)   // 心跳: 不依赖 I2 (P0-03)
                D("[HEARTBEAT] TMP seen=" + TmpSeen + " fixed=" + TmpFixed + " miss=" + TmpMiss
                  + " cjkSkip=" + TmpCjkSkip
                  + " uniqHit=" + SeenHit.Count + " uniqMiss=" + SeenMiss.Count);

            // 0) v1.3.7 (C6): 含 CJK 的写入是译文回流(AT/本插件替换后的二次 set)。原文全英,
            //    不可能命中英文键 —— 直接放行, 不进模板/词典/MISS 统计, 防 SeenMiss 被噪声占满。
            if (HasCjk(s)) { TmpCjkSkip++; return; }

            // 1) 道具获得复合弹窗(多行含 color) (P0-2): 用原串处理, 逐行翻译保结构
            if (s.IndexOf("ITEM GET", StringComparison.OrdinalIgnoreCase) >= 0 && s.IndexOf('\n') >= 0)
            {
                string ig = TryItemGet(s);
                if (ig != null) { D("[ITEMGET HIT] " + Trunc(s) + " -> " + Trunc(ig)); __0 = ig; TmpFixed++; return; }
            }

            string key = Norm(s);
            if (key.Length < 1) return;

            // 2) 日期+时段模板 (P0-3)
            var mDt = DayTimeRe.Match(key);
            if (mDt.Success)
            {
                string dd, tt;
                if (DayMap.TryGetValue(mDt.Groups[1].Value, out dd) && TimeMap.TryGetValue(mDt.Groups[2].Value, out tt))
                {
                    string sep = s.IndexOf('\n') >= 0 ? "\n" : " ";
                    string dt = dd + sep + tt;
                    D("[DAYTIME HIT] " + Trunc(key) + " -> " + Trunc(dt));
                    __0 = dt; TmpFixed++; return;
                }
            }

            // 3) 单独 "Acquired {n}x" (P1-01)
            var mAcq = AcquiredRe.Match(key);
            if (mAcq.Success) { __0 = "获得了 " + mAcq.Groups[1].Value + " 个"; TmpFixed++; LogTarget(s, key, true, __instance); return; }

            // 4) 整句词典 (v1.3.7 C1: 命中后保留运行时整句 <color> 包裹)
            string zh;
            bool hit = Disp.TryGetValue(key, out zh) && !string.IsNullOrEmpty(zh);
            LogTarget(s, key, hit, __instance);   // 目标串无条件记录 (P0-04)
            if (hit)
            {
                if (SeenHit.Add(key)) D("[TMP HIT ] \"" + Trunc(s) + "\"");
                __0 = RewrapColor(s, zh); TmpFixed++; return;
            }

            // 5) v1.3.7 (C2): 数字参数化整句 —— 运行时 string.Format 代入数字的组合串
            //    (如 GOLDEN_GIRLS_INFO "Collected fireflies: 3")整句词典必不命中;
            //    把数字抠成 {0},{1}... 再查模板键(词典生成自带 "Collected fireflies: {0}" 等模板)。
            string ntpl = TryNumTemplate(key);
            if (ntpl != null)
            {
                D("[NUMTPL HIT] " + Trunc(key) + " -> " + Trunc(ntpl));
                __0 = RewrapColor(s, ntpl); TmpFixed++; return;
            }

            // 6) v1.3.7 (C2): 恋人弹窗 "<b>名字['s]</b> \n 后缀" 两段式(PopupLauncher 运行时拼接,
            //    名字 × 后缀组合词典难穷举; 两段分别查词典后重建结构)。
            string rom = TryRomance(key);
            if (rom != null)
            {
                D("[ROMANCE HIT] " + Trunc(key) + " -> " + Trunc(rom));
                __0 = rom; TmpFixed++; return;
            }

            if (SeenMiss.Count < 5000 && SeenMiss.Add(key)) D("[TMP MISS] \"" + Trunc(key) + "\" @" + CompPath(__instance));
            TmpMiss++;
        }

        // v1.3.7 (C6): 是否含 CJK(含全角/CJK 标点)字符
        private static bool HasCjk(string s)
        {
            for (int i = 0; i < s.Length; i++) if (IsCjk(s[i])) return true;
            return false;
        }

        // v1.3.7 (C1): 检测整句被单一 <color=...>...</color> 包裹(思考独白 thoughtColor /
        // 恐怖台词 horrorColor 由 DialogueWindow 运行时整句包色)。返回开标签, 未包裹返回 null。
        // 深度扫描: 外层开标签若在结尾之前就被闭合(如 "<c>A</c> x <c>B</c>")则不算整句包裹。
        private static string WholeWrapOpen(string s)
        {
            if (s.Length < 16 || s[0] != '<') return null;
            if (!s.StartsWith("<color=", StringComparison.OrdinalIgnoreCase)) return null;
            if (!s.EndsWith("</color>", StringComparison.OrdinalIgnoreCase)) return null;
            int gt = s.IndexOf('>');
            if (gt < 0) return null;
            int endTag = s.Length - 8;   // 末尾 "</color>" 的起点
            int depth = 1, i = gt + 1;
            while (i < s.Length)
            {
                int lt = s.IndexOf('<', i);
                if (lt < 0) break;
                if (lt + 8 <= s.Length && string.Compare(s, lt, "</color>", 0, 8, StringComparison.OrdinalIgnoreCase) == 0)
                {
                    depth--;
                    if (depth == 0) return lt == endTag ? s.Substring(0, gt + 1) : null;
                    i = lt + 8;
                }
                else if (lt + 6 <= s.Length && string.Compare(s, lt, "<color", 0, 6, StringComparison.OrdinalIgnoreCase) == 0)
                {
                    depth++; i = lt + 6;
                }
                else i = lt + 1;
            }
            return null;
        }

        // v1.3.7 (C1): 原串整句包色而词典值不含运行时包裹时回包。同时修复 LogMenu 对恐怖行的
        // ReplaceFirstOccurrence(text, horrorCode, ...) —— 回包后译文重新含 horrorColor hex。
        private static int WrapLogged;
        private static string RewrapColor(string orig, string zh)
        {
            string open = WholeWrapOpen(orig);
            if (open == null) return zh;
            if (WholeWrapOpen(zh) != null) return zh;   // 词典值已整句包裹, 不重复包
            if (WrapLogged < 50) { WrapLogged++; D("[WRAP] 回包 " + open + " : " + Trunc(zh)); }
            return open + zh + "</color>";
        }

        // v1.3.7 (C2): 数字模板 —— 把 key 中的数字串依次替换为 {0},{1}... 查词典模板键。
        private static string TryNumTemplate(string key)
        {
            if (key.Length > 300) return null;
            bool hasDigit = false, hasAlpha = false;
            for (int i = 0; i < key.Length; i++)
            {
                char c = key[i];
                if (char.IsDigit(c)) hasDigit = true;
                else if (char.IsLetter(c)) hasAlpha = true;
            }
            if (!hasDigit || !hasAlpha) return null;   // 纯数字/无字母串不模板化
            var nums = new List<string>();
            string tpl = NumRe.Replace(key, delegate(System.Text.RegularExpressions.Match m)
            {
                nums.Add(m.Value);
                return "{" + (nums.Count - 1) + "}";
            });
            if (nums.Count > 4) return null;
            string zh;
            if (!(Disp.TryGetValue(tpl, out zh) && !string.IsNullOrEmpty(zh))) return null;
            for (int i = 0; i < nums.Count; i++) zh = zh.Replace("{" + i + "}", nums[i]);
            return zh;
        }

        // v1.3.7 (C2): 恋人弹窗两段式。实机与反编译存在两种形态(带 's + 原版错拼 "Aquired" /
        // 不带 's + "Acquired"), 正则同时覆盖; 名字与后缀分别查词典, 后缀缺失用 refkey 词典同源兜底。
        private static string TryRomance(string key)
        {
            var m = RomanceRe.Match(key);
            if (!m.Success) return null;
            string name = m.Groups[1].Value;
            bool poss = m.Groups[2].Success && m.Groups[2].Value.Length > 0;
            string tail = m.Groups[3].Value;
            string zhName, zhTail;
            if (!(Disp.TryGetValue(name, out zhName) && !string.IsNullOrEmpty(zhName))) zhName = name;
            if (!(Disp.TryGetValue(tail, out zhTail) && !string.IsNullOrEmpty(zhTail)))
            {
                if (tail.StartsWith("Heart Piece", StringComparison.OrdinalIgnoreCase)) zhTail = "获得爱心碎片!";
                else if (tail.StartsWith("Everlasting", StringComparison.OrdinalIgnoreCase)) zhTail = "永恒之爱!";
                else zhTail = "深厚羁绊";
            }
            return "<b>" + zhName + (poss ? "的" : "") + "</b>\n" + zhTail;
        }

        // 逐行翻译道具复合串, 保留换行与颜色标签 (P0-2)
        private static string TryItemGet(string s)
        {
            var lines = s.Replace("\r", "").Split('\n');
            bool any = false;
            for (int i = 0; i < lines.Length; i++)
            {
                string ln = lines[i].Trim();
                if (ln.Length == 0) continue;
                var m = AcqItemRe.Match(ln);
                if (m.Success)
                {
                    string cnt = m.Groups[1].Value;
                    string colorOpen = m.Groups[2].Value;   // <color=red> 或 ""
                    string name = m.Groups[3].Value;
                    string zhName, nk = Norm(name);
                    // v1.3.18 (F1): 道具上下文优先查专用映射 —— Lebkuchen 在道具弹窗
                    // 是"姜饼"而非角色名"斯佩尔特"; 未命中再回退 display 词典。
                    if (!(ItemNames.TryGetValue(nk, out zhName) && !string.IsNullOrEmpty(zhName)) &&
                        !(Disp.TryGetValue(nk, out zhName) && !string.IsNullOrEmpty(zhName)))
                    { zhName = name; D("[ITEM_NAME MISS] " + Trunc(name)); }
                    string colorClose = string.IsNullOrEmpty(colorOpen) ? "" : "</color>";
                    lines[i] = "获得了 " + cnt + " 个 " + colorOpen + zhName + colorClose;
                    any = true; continue;
                }
                string zh;
                if (Disp.TryGetValue(Norm(ln), out zh) && !string.IsNullOrEmpty(zh)) { lines[i] = zh; any = true; }
            }
            return any ? string.Join("\n", lines) : null;
        }

        // 组件层级路径(诊断右侧栏目丝带是否 TMP 文本) (P1)
        private static string CompPath(object inst)
        {
            try
            {
                var comp = inst as UnityEngine.Component;
                if (comp == null) return "?";
                var t = comp.transform;
                string p = comp.name;
                for (int i = 0; i < 5 && t != null && t.parent != null; i++) { t = t.parent; p = t.name + "/" + p; }
                return p;
            }
            catch { return "?"; }
        }

        private static void LogTarget(string orig, string key, bool hit, object inst)
        {
            for (int i = 0; i < Targets.Length; i++)
                if (key.IndexOf(Targets[i], StringComparison.OrdinalIgnoreCase) >= 0)
                { D("[TARGET " + (hit ? "HIT " : "MISS") + "] orig=\"" + Trunc(orig) + "\" key=\"" + Trunc(key) + "\" @" + CompPath(inst)); return; }
        }


        // 诊断文件(即时 flush, 避免 LogOutput 被过早复制而看不到运行时记录)
        private void OpenDiag()
        {
            try
            {
                string loc = Assembly.GetExecutingAssembly().Location;
                string dir = Path.GetDirectoryName(loc);
                Diag = new System.IO.StreamWriter(Path.Combine(dir, "DIAG.txt"), false,
                    new System.Text.UTF8Encoding(false));
                Diag.AutoFlush = true;
                Diag.WriteLine("=== LGTS DIAG v" + VER + " 启动 ===");
                try { Diag.WriteLine("DLL=" + loc); Diag.WriteLine("DLL time=" + File.GetLastWriteTime(loc)); } catch { }
            }
            catch (Exception e) { Log.LogWarning("DIAG 打开失败: " + e.Message); }
        }
        internal static void D(string line)
        {
            try { if (Diag != null) Diag.WriteLine(line); } catch { }
        }

        // v1.3.7 (B4): 统一汇总行。真正的 [FINAL] 只在应用退出(Application.quitting)时写出;
