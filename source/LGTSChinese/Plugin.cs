        // ---- 旧版 UGUI Text 兜底 (v1.3.5, 丝带空白单项修复) ----
        // 暂停菜单五条丝带(PauseMenu/HomeMenu/Options/*)是旧版 UnityEngine.UI.Text,
        // 字体 "Adorn Serif" 为 295 字形的静态位图字体, 写入中文后无字形可画 → 空白。
        // 主修复是 AT 的 OverrideFont=Microsoft YaHei; 本循环是确定性兜底:
        // 1) 文本为英文且词典命中 → 补翻(AT 失效时也能出中文);
        // 2) 文本含 CJK 但所用静态字体画不出 → 换成系统动态中文字体。
        // 每 2 秒扫一次(含未激活对象, 菜单打开前即已修好); 旧版 Text 全游戏仅几十个, 开销可忽略。
        private static Font CjkOsFont;
        private static bool CjkOsFontProbed;
        internal static int UguiTextFixed, UguiFontFixed;
        private static readonly HashSet<int> UguiLoggedIds = new HashSet<int>();

        internal static IEnumerator UguiFixLoop()
        {
            // 用 Realtime: 启动/加载期 timeScale 可能为 0, 普通 WaitForSeconds 会永远不醒
            yield return new WaitForSecondsRealtime(3f);
            if (!CjkOsFontProbed)
            {
                CjkOsFontProbed = true;
                string[] cands = { "Microsoft YaHei", "微软雅黑", "Microsoft YaHei UI", "SimHei", "黑体", "SimSun", "宋体" };
            try
            {
                var os = new HashSet<string>(Font.GetOSInstalledFontNames(), StringComparer.OrdinalIgnoreCase);
                var hit = new List<string>();
                foreach (var c in cands) if (os.Contains(c)) hit.Add(c);
                D("[UGUI FONT] 系统字体数=" + os.Count + " 候选命中=[" + string.Join(",", hit.ToArray()) + "]");
            }
            catch (Exception e) { D("[UGUI FONT] GetOSInstalledFontNames 失败: " + e.Message); }
            foreach (var name in cands)
            {
                Font f = null;
                try
                {
                    f = Font.CreateDynamicFontFromOSFont(name, 32);
                    if (f != null && f.HasCharacter('道')) { CjkOsFont = f; D("[UGUI FONT] 采用系统字体: " + name); break; }
                    if (f != null) D("[UGUI FONT] " + name + " 创建成功但无'道'字形, 弃用");
                }
                catch (Exception e) { D("[UGUI FONT] " + name + " 创建失败: " + e.Message); }
            }
            if (CjkOsFont == null)
                D("[UGUI FONT] 无可用系统中文字体, 兜底仅做词典补翻(丝带将依赖 AT OverrideFont)");
            }
            while (true)
            {
                try { UguiScan(); }
                catch (Exception e) { D("[UGUI SCAN] 异常: " + e.Message); }
                yield return new WaitForSecondsRealtime(2f);
            }
        }


        private static void UguiScan()
        {
            var texts = UnityEngine.Object.FindObjectsOfType<UnityEngine.UI.Text>(true);
            for (int i = 0; i < texts.Length; i++)
            {
                var t = texts[i];
                if (t == null) continue;
                string s = t.text;
                if (string.IsNullOrEmpty(s)) continue;

                // 1) 词典补翻(仅纯非中文文本; 幂等, AT 已翻则跳过)
                char firstCjk = '\0';
                for (int k = 0; k < s.Length; k++) if (Core.IsCjk(s[k])) { firstCjk = s[k]; break; }
                if (firstCjk == '\0')
                {
                    string zh;
                    if (Disp.TryGetValue(Core.Norm(s), out zh) && !string.IsNullOrEmpty(zh) && zh != s)
                    {
                        t.text = zh; s = zh; UguiTextFixed++;
                        for (int k = 0; k < s.Length; k++) if (Core.IsCjk(s[k])) { firstCjk = s[k]; break; }
                        if (UguiLoggedIds.Count < 200 && UguiLoggedIds.Add(t.GetInstanceID()))
                            D("[UGUI TEXT] " + CompPath(t) + " -> " + Trunc(zh));
                    }
                }

                // 2) 字体兜底: 含 CJK 但静态字体无该字形(动态字体不动, 交给 OS fallback)
                if (CjkOsFont != null && firstCjk != '\0')
                {
                    var f = t.font;
                    bool bad = f == null;
                    if (!bad) { try { bad = !f.dynamic && !f.HasCharacter(firstCjk); } catch { bad = false; } }
                    if (bad)
                    {
                        string oldName = f != null ? f.name : "<null>";
                        t.font = CjkOsFont;
                        if (t.fontSize <= 0) t.fontSize = 24;
                        UguiFontFixed++;
                        D("[UGUI FONT FIX] " + CompPath(t) + " font " + oldName + " -> " + CjkOsFont.name + " text=" + Trunc(s));
                    }
                }
            }
        }

        // ---- 中文字体回退: 加载 CJK TMP 字体资产作为全局 fallback ----
        // 通道1(外部): AT 配置 FallbackFontTextMeshPro=arialuni_sdf_u2019(游戏根目录, 必装件)。
        // 通道2(可选): 插件目录 font/lgts_cjk (AssetBundle, 内含一个 TMP_FontAsset)。
        // 通道3(v1.3.7, C5): 前两者以外的运行时兜底 —— 用系统中文字体动态生成 TMP_FontAsset,
        //   消除"TMP 字形单点依赖 arialuni"; 任一步失败仅记日志, 不影响其他通道。
        private static bool TmpFallbackDone;
        private static bool FontBundleWarned;   // v1.3.7 (C5): 缺字体包提示只发一次(Runner 会反复重建)
        private static Font OsTmpFontKeepRef;   // 持引用防动态字体被回收
        internal static IEnumerator SetupFontFallback()
        {
            yield return new WaitForSecondsRealtime(2f); // 等 TMP 初始化(Realtime: 防 timeScale=0)
            if (TmpFallbackDone) yield break;
            string dir = Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location);
            string bundlePath = Path.Combine(dir, "font", "lgts_cjk");
            if (!File.Exists(bundlePath))
            {
                if (!FontBundleWarned)
                {
                    FontBundleWarned = true;
                    Log.LogInfo("未找到可选字体包 font/lgts_cjk。TMP 中文字形以 AT 的 arialuni 回退为主, 尝试生成系统字体运行时兜底。");
                    TryOsTmpFallback();
                    // v1.3.31: 两条通道都失败才算降级 —— 字形仍可由 arialuni 承担, 但必须在 DIAG 里可见。
                    if (!TmpFallbackDone) Degrade("中文字体未注入 TMP 全局 fallback; 字形依赖 arialuni/UGUI 通道");
                }
                yield break;
            }
            AssetBundle ab = null;
            try { ab = AssetBundle.LoadFromFile(bundlePath); }
            catch (Exception e) { Log.LogError("字体包加载失败: " + e); yield break; }
            if (ab == null) yield break;
            try
            {
                // 反射操作 TMPro 以避免硬依赖版本
                Type fontType = AccessTools.TypeByName("TMPro.TMP_FontAsset");
                if (fontType == null) { Log.LogError("未找到 TMPro.TMP_FontAsset"); yield break; }
                var loadAll = typeof(AssetBundle).GetMethod("LoadAllAssets", new Type[] { typeof(Type) });
                var assets = loadAll.Invoke(ab, new object[] { fontType }) as UnityEngine.Object[];
                if (assets == null || assets.Length == 0) { Log.LogError("字体包内无 TMP_FontAsset"); yield break; }
                UnityEngine.Object cjk = assets[0];
                if (InjectTmpFallback(cjk))
                {
                    TmpFallbackDone = true;
                    Log.LogInfo("已注入中文字体到 TMP 全局 fallback。");
                    D("[TMP FONT] 已注入 lgts_cjk 到全局 fallback");
                }
                else Log.LogWarning("无法注入 TMP fallback(版本差异), 可改为逐字体注入。");
                if (!TmpFallbackDone) Degrade("中文字体未注入 TMP 全局 fallback; 字形依赖 arialuni/UGUI 通道");
            }
            finally
            {
                // v1.3.27 (G2): 注入后卸载包体。Unload(false) 只释放包, 已 LoadAllAssets 的
                // TMP_FontAsset 仍由 fallback 列表持有, 字形继续可用。
                if (ab != null) { try { ab.Unload(false); } catch { } }
            }
        }

        // v1.3.7 (C5): 系统中文字体 → 动态 TMP_FontAsset → TMP 全局 fallback。
        private static void TryOsTmpFallback()
        {
            try
            {
                Font os = null;
                string[] cands = { "Microsoft YaHei", "微软雅黑", "Microsoft YaHei UI", "SimHei", "黑体", "SimSun", "宋体" };
                foreach (var name in cands)
                {
                    try
                    {
                        var f = Font.CreateDynamicFontFromOSFont(name, 32);
                        if (f != null && f.HasCharacter('道')) { os = f; break; }
                    }
                    catch { }
                }
                if (os == null) { D("[TMP FONT] 无可用系统中文字体, OS 动态兜底跳过"); return; }
                Type fontType = AccessTools.TypeByName("TMPro.TMP_FontAsset");
                if (fontType == null) { D("[TMP FONT] 未找到 TMP_FontAsset, OS 动态兜底跳过"); return; }
                MethodInfo create = fontType.GetMethod("CreateFontAsset",
                    BindingFlags.Public | BindingFlags.Static, null, new Type[] { typeof(Font) }, null);
                if (create == null) { D("[TMP FONT] 无 CreateFontAsset(Font) 重载, OS 动态兜底跳过"); return; }
                var asset = create.Invoke(null, new object[] { os }) as UnityEngine.Object;
                if (asset == null) { D("[TMP FONT] CreateFontAsset 返回空, OS 动态兜底跳过"); return; }
                if (InjectTmpFallback(asset))
                {
                    TmpFallbackDone = true;
                    OsTmpFontKeepRef = os;
                    Log.LogInfo("已用系统字体生成 TMP 动态字形兜底并注入全局 fallback。");
                    D("[TMP FONT] OS 动态字形兜底注入成功: " + os.name);
                }
                else D("[TMP FONT] OS 动态字形生成成功但注入 fallback 失败");
            }
            catch (Exception e) { D("[TMP FONT] OS 动态兜底失败(不影响 arialuni 通道): " + e.Message); }
        }

        // 把一个 TMP_FontAsset 加入 TMP_Settings 全局 fallback 列表(反射, 版本差异防御)。
        private static bool InjectTmpFallback(UnityEngine.Object cjk)
        {
            try
            {
                Type settings = AccessTools.TypeByName("TMPro.TMP_Settings");
                if (settings == null) return false;
                var instProp = settings.GetProperty("instance", BindingFlags.NonPublic | BindingFlags.Static | BindingFlags.Public);
                var inst = instProp != null ? instProp.GetValue(null, null) : null;
                var fallbackField = settings.GetField("m_fallbackFontAssets", BindingFlags.NonPublic | BindingFlags.Instance);
                if (inst == null || fallbackField == null) return false;
                var list = fallbackField.GetValue(inst) as IList;
                if (list == null) return false;
                list.Add(cjk);
                return true;
            }
            catch (Exception e) { D("[TMP FONT] fallback 注入异常: " + e.Message); return false; }
        }
    }

    // 独立协程宿主: 游戏启动早期会销毁 BepInEx 插件宿主, 协程必须挂在这里。
    // 若本对象也被销毁, Tmp_Prefix 会在下一次任意 TMP 文本写入时重建它。
    internal class UguiRunner : MonoBehaviour
    {
        private void Awake()
        {
            Plugin.Runner = this;
            Plugin.D("[RUNNER] 启动");
            StartCoroutine(Plugin.SetupFontFallback());
            StartCoroutine(Plugin.UguiFixLoop());
        }
        private void OnDestroy()
        {
            if (Plugin.Runner == this) Plugin.Runner = null;
            Plugin.D("[RUNNER] 被销毁" + (Plugin.Quitting ? "(应用退出)" : "(等待 TMP 钩子重建)"));
        }
    }
