            PatchGetTranslation(harmony);
            PatchDoLocalize(harmony);
            PatchLocalizeGuard(harmony);
            PatchTmp(harmony);
            PatchGridlyProbe(harmony);   // v1.3.32 探针: 物品/UI 的取词汇聚点
            // 本作会在启动早期销毁 BepInEx 的插件宿主(DIAG 中 [HOST DESTROYED] 紧跟启动即证据),
            // 挂在本组件上的协程活不过第一帧, 因此协程一律放到自愈的独立 Runner 上,
            // Runner 被销毁后由 TMP 钩子在下次任意文本写入时重建。
            // v1.3.7 (B4): 真正的 [FINAL] 汇总在 Application.quitting 时写出;
            // 宿主 OnDestroy 发生在启动期, 其汇总行改名 [HOST DESTROYED] 以免误导排障。
            try { Application.quitting += OnAppQuitting; } catch { }
            EnsureRunner();
            Log.LogInfo("LGTS 中文插件已加载, 词条 " + Zh.Count + " 条。");
        }

        // 载入显示词典。优先单一确定性文件 translation/lgts_display.json(去标签英文->含标签中文);
        // 缺失时退回 AT 的 *.txt(纯文本)。(修 P1-04 确定性 / P0-05 计数口径)
        private void LoadDisplayDict()
        {
            try
            {
                string dir = Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location);
                string js = Path.Combine(dir, "translation", "lgts_display.json");
                if (File.Exists(js))
                {
                    Core.ParseFlatJson(File.ReadAllText(js, System.Text.Encoding.UTF8), Disp);
                    D("显示词典(lgts_display.json)载入: " + Disp.Count + " 归一键");
                    Log.LogInfo("显示词典载入: " + Disp.Count + " 条 (lgts_display.json)");
                    if (Disp.Count < Core.MinDisplayEntries)
                    {
                        D("[WARN] 显示词典仅 " + Disp.Count + " 条, 低于预期 " + Core.MinDisplayEntries + " —— 文件可能损坏或被截断");
                        Log.LogWarning("显示词典条目异常偏少: " + Disp.Count + " 条 (预期 > " + Core.MinDisplayEntries + ")");
                        Degrade("显示词典仅 " + Disp.Count + " 条 (< " + Core.MinDisplayEntries + "), 疑似被截断");
                    }
                    return;
                }
                Degrade("显示词典 lgts_display.json 不存在, 退回 AT 文本词典合并");
                // 退回: 载入 AT 文本词典(仅跳 3 个控制文件), 确定性排序, 主词典优先, UI 覆盖
                string tdir = Path.GetFullPath(Path.Combine(dir, "..", "..", "Translation", "zh", "Text"));
                if (!System.IO.Directory.Exists(tdir)) { D("显示词典目录不存在: " + tdir); return; }
                var files = new List<string>(System.IO.Directory.GetFiles(tdir, "*.txt"));
                // 显式顺序: 主词典先, UI 后(UI 可覆盖)
                files.Sort((a, b) =>
                {
                    int ra = Path.GetFileName(a) == "_AutoGeneratedTranslations.txt" ? 0 : 1;
                    int rb = Path.GetFileName(b) == "_AutoGeneratedTranslations.txt" ? 0 : 1;
                    return ra != rb ? ra - rb : string.CompareOrdinal(a, b);
                });
                int conflict = 0;
                foreach (var fp in files)
                {
                    string fn = Path.GetFileName(fp);
                    if (fn == "_Substitutions.txt" || fn == "_Preprocessors.txt" || fn == "_Postprocessors.txt")
                        continue;
                    int rows = 0;
                    foreach (var raw in File.ReadAllLines(fp, System.Text.Encoding.UTF8))
                    {
                        if (raw.Length == 0 || raw[0] == '#') continue;
                        int eq = raw.IndexOf('=');
                        if (eq <= 0) continue;
                        string k = Core.Norm(raw.Substring(0, eq).Replace("\\n", " "));
                        string v = raw.Substring(eq + 1).Replace("\\n", "\n");
                        if (k.Length == 0 || v.Length == 0) continue;
                        rows++;
                        string old;
                        if (Disp.TryGetValue(k, out old)) { if (old != v) conflict++; Disp[k] = v; }  // 后者(UI)覆盖
                        else Disp[k] = v;
                    }
                    D("  词典文件 " + fn + ": 有效行 " + rows);
                }
                D("显示词典(退回 AT 文本)载入: " + Disp.Count + " 归一键, 冲突覆盖 " + conflict);
                Log.LogInfo("显示词典载入: " + Disp.Count + " 条 (AT 文本退回)");
            }
            catch (Exception e) { D("显示词典载入失败: " + e); Log.LogWarning("显示词典载入失败: " + e.Message); Degrade("显示词典载入异常: " + e.Message); }
        }

        // v1.3.18 (F1): 道具名专用映射 —— ITEM GET 弹窗的道具英文短名与角色名牌共用
        // 同一英文串(Lebkuchen 既是角色"斯佩尔特"又是食品"姜饼"), display 词典在弹窗
        // 上下文无从区分, 旧版弹窗因此把姜饼显示成"斯佩尔特"。此表由离线脚本
        // (fix_batches_*/batch6_gen_item_names.py)从 Gridly ITM_*_N_* 名称记录 ×
        // refkey 译文生成, 键归一规则与 Core.Norm() 一致。文件缺失时静默降级(空表),
        // TryItemGet 回退 display 词典, 行为与旧版完全一致。
        private void LoadItemNames()
        {
            try
            {
                string dir = Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location);
                string js = Path.Combine(dir, "translation", "lgts_item_names.json");
                if (!File.Exists(js)) { D("道具名映射(lgts_item_names.json)不存在, 跳过"); Degrade("道具名映射缺失, 道具名回退整句词典(名/物同形时可能选错)"); return; }
                Core.ParseFlatJson(File.ReadAllText(js, System.Text.Encoding.UTF8), ItemNames);
                D("道具名映射(lgts_item_names.json)载入: " + ItemNames.Count + " 键");
                Log.LogInfo("道具名映射载入: " + ItemNames.Count + " 条 (lgts_item_names.json)");
                if (ItemNames.Count == 0) Degrade("道具名映射载入 0 条");
            }
            catch (Exception e) { D("道具名映射载入失败: " + e.Message); Log.LogWarning("道具名映射载入失败: " + e.Message); Degrade("道具名映射载入异常: " + e.Message); }
        }

        // 尝试挂钩 TMP 文本入口(base set_text 在本作会 IL 失败; SetText 方法多半可挂)。
        private void PatchTmp(Harmony harmony)
        {
            var pre = new HarmonyMethod(typeof(Plugin).GetMethod("Tmp_Prefix",
                BindingFlags.Static | BindingFlags.NonPublic));
            pre.priority = Priority.First;   // 让 LGTS 先于 AT 拿到原始整句 (P1-03)
            Type t = AccessTools.TypeByName("TMPro.TMP_Text");
            if (t == null) { Log.LogWarning("未找到 TMPro.TMP_Text"); D("未找到 TMP_Text"); return; }
            var setter = t.GetMethod("set_text", BindingFlags.Public | BindingFlags.Instance,
                null, new Type[] { typeof(string) }, null);
            if (setter != null) TryPatch(harmony, setter, pre, "TMP_Text.set_text");
            else D("TMP hook ABSENT: set_text 未找到");   // v1.3.7 (C7): 未找到也显式记录
            var setText = t.GetMethod("SetText", BindingFlags.Public | BindingFlags.Instance,
                null, new Type[] { typeof(string) }, null);
            if (setText != null) TryPatch(harmony, setText, pre, "TMP_Text.SetText(string)");
            else D("TMP hook ABSENT: SetText(string) 未找到(本 TMP 版本该重载多为 SetText(string,bool) 默认参形态, 会绕回已挂路径)");
            // 部分调用走 SetText(string, bool)
            var setText2 = t.GetMethod("SetText", BindingFlags.Public | BindingFlags.Instance,
                null, new Type[] { typeof(string), typeof(bool) }, null);
            if (setText2 != null) TryPatch(harmony, setText2, pre, "TMP_Text.SetText(string,bool)");
            else D("TMP hook ABSENT: SetText(string,bool) 未找到");
        }
        private void TryPatch(Harmony harmony, MethodInfo m, HarmonyMethod pre, string label)
        {
            try { harmony.Patch(m, prefix: pre); Log.LogInfo("已挂钩 " + label); D("TMP hook OK: " + label); }
            catch (Exception e) { Log.LogWarning("挂钩 " + label + " 失败: " + e.Message); D("TMP hook FAIL: " + label + " : " + e.Message); }
        }

        // TMP 渲染层前置: __0 = 即将显示的文本; __instance = TMP 组件(取路径供诊断)。
        // v1.3.10: 热钩子顶层 try/catch 纵深防御 —— 钩内任何异常不得中断游戏写入流程(P2-3)。
        private static int HookErr;
        private static void Tmp_Prefix(ref string __0, object __instance)
        {
            try { Tmp_PrefixCore(ref __0, __instance); }
            catch (Exception e) { if (HookErr < 20) { HookErr++; D("[HOOK ERR] TMP: " + e.Message); } }
        }
        private static void Tmp_PrefixCore(ref string __0, object __instance)
        {
            if (Runner == null) EnsureRunner();   // 宿主被销毁则借热路径重建 (v1.3.5)
            string s = __0;
            if (string.IsNullOrEmpty(s)) return;
            TmpSeen++;
            if (TmpSeen % 500 == 0)   // 心跳: 不依赖 I2 (P0-03)
                D("[HEARTBEAT] TMP seen=" + TmpSeen + " fixed=" + TmpFixed + " miss=" + TmpMiss
                  + " missNoise=" + TmpMissNoise + " degrade=" + DegradeCount
                  + " cjkSkip=" + TmpCjkSkip
                  + " uniqHit=" + SeenHit.Count + " uniqMiss=" + SeenMiss.Count);

            // 0) v1.3.7 (C6): 含 CJK 的写入是译文回流(AT/本插件替换后的二次 set)。原文全英,
            //    不可能命中英文键 —— 直接放行, 不进模板/词典/MISS 统计, 防 SeenMiss 被噪声占满。
            if (Core.HasCjk(s)) { TmpCjkSkip++; return; }

            // 1) 道具获得复合弹窗(多行含 color) (P0-2): 用原串处理, 逐行翻译保结构
            if (s.IndexOf("ITEM GET", StringComparison.OrdinalIgnoreCase) >= 0 && s.IndexOf('\n') >= 0)
            {
                string ig = TryItemGet(s);
                if (ig != null) { D("[ITEMGET HIT] " + Trunc(s) + " -> " + Trunc(ig)); __0 = ig; TmpFixed++; return; }
            }

            string key = Core.Norm(s);
            if (key.Length < 1) return;

            // 1.5~3) v1.3.33 结构侧: 六条模板规则(存档时间戳 / 数量角标 / 回合数 / 续关花费 /
            //     日期时段 / 单独获得)统一由 Core.MatchRule 判定。规则本身搬进 Core.cs 以后
            //     可以在游戏外用 selftest 逐条验; 这里只做 DIAG 与上屏。
            //     判定顺序与 v1.3.32 实机 DIAG 验证过的顺序逐条一致 —— 改顺序等于改上屏结果。
            string ruleZh;
            RuleHit ruleHit = Core.MatchRule(key, s, out ruleZh);
            if (ruleHit != RuleHit.None)
            {
                D("[" + Core.RuleLabel(ruleHit) + "] " + Trunc(key) + " -> " + Trunc(ruleZh.Replace("\n", "\\n")));
                if (ruleHit == RuleHit.Acquired) LogTarget(s, key, true, __instance);
                __0 = ruleZh; TmpFixed++; return;
            }

            // 3.5) v1.3.30 (F2): 道具名位 —— 先查 lgts_item_names.json, 未命中再回退整句词典。
            //      Lebkuchen 既是角色名("斯佩尔特")又是食品名("姜饼"), 显示词典按英文归一只
            //      能二选一, 旧版因此把商店列表/道具详情/背包/HUD 上的姜饼都显示成角色名。
            //      这些位置与角色名牌的差别只在组件路径上, 所以按路径判上下文。
            bool hudToast;
            if (ItemNameCtx(__instance, key, out hudToast))
            {
                if (hudToast)
                {
                    // HUD 小提示是运行时拼接的 "名字 xN", 照 ITEM GET 弹窗的口径拆名字与数量,
                    // 中文侧沿用译本已有的「名字 ×N」形(参见 XUAT_03177 Item x5 -> 道具 ×5)。
                    var mq = Core.ItemQtyRe.Match(key);
                    if (mq.Success)
                    {
                        string zhQ = LookupItemName(Core.Norm(mq.Groups[1].Value));
                        if (zhQ != null)
                        {
                            string rebuilt = zhQ + " ×" + mq.Groups[2].Value;
                            D("[ITEMNAME HUD] " + Trunc(key) + " -> " + Trunc(rebuilt));
                            __0 = rebuilt; TmpFixed++; return;
                        }
                    }
                }
                string zhItem = LookupItemName(key);
                if (zhItem != null)
                {
                    if (SeenHit.Add(key)) D("[ITEMNAME HIT] \"" + Trunc(s) + "\" @" + CompPath(__instance));
                    __0 = RewrapColor(s, zhItem); TmpFixed++; return;
                }
            }

            // 4) 整句词典 (v1.3.7 C1: 命中后保留运行时整句 <color> 包裹)
            string zh;
            bool hit = Disp.TryGetValue(key, out zh) && !string.IsNullOrEmpty(zh);
            LogTarget(s, key, hit, __instance);   // 目标串无条件记录 (P0-04)
            if (hit)
            {
                // v1.3.30 (F2) 自我诊断: 这一串既是道具名、又在这里被显示成了别的意思 ——
                // 说明该文本位没被 ItemNameCtx 认出来(规则漏了某条路径), 或它本来就是角色名牌。
                // 每条 键+路径 只记一次, 一次实机跑完看 DIAG 就知道规则够不够。
                if (ItemNames.ContainsKey(key))
                {
                    string zhItem0;
                    if (ItemNames.TryGetValue(key, out zhItem0) && !string.IsNullOrEmpty(zhItem0) && zhItem0 != zh)
                    {
                        string cp0 = CompPath(__instance);
                        if (SeenNameCollide.Add(key + "|" + cp0))
                            D("[NAME COLLIDE] \"" + Trunc(key) + "\" 显示词典=" + Trunc(zh)
                              + " 道具名表=" + Trunc(zhItem0) + " @" + cp0);
                    }
                }
                if (SeenHit.Add(key)) D("[TMP HIT ] \"" + Trunc(s) + "\"");
                __0 = RewrapColor(s, zh); TmpFixed++; return;
            }

            // 5) v1.3.7 (C2): 数字参数化整句 —— 运行时 string.Format 代入数字的组合串
            //    (如 GOLDEN_GIRLS_INFO "Collected fireflies: 3")整句词典必不命中;
            //    把数字抠成 {0},{1}... 再查模板键(词典生成自带 "Collected fireflies: {0}" 等模板)。
            string ntpl = TryNumTemplate(key);
            if (ntpl != null)
            {
                D("[NUMTPL HIT] " + Trunc(key) + " -> " + Trunc(ntpl));
                __0 = RewrapColor(s, ntpl); TmpFixed++; return;
            }

            // 6) v1.3.7 (C2): 恋人弹窗 "<b>名字['s]</b> \n 后缀" 两段式(PopupLauncher 运行时拼接,
            //    名字 × 后缀组合词典难穷举; 两段分别查词典后重建结构)。
            string rom = TryRomance(key);
            if (rom != null)
            {
                D("[ROMANCE HIT] " + Trunc(key) + " -> " + Trunc(rom));
                __0 = rom; TmpFixed++; return;
            }

            // v1.3.31 (结构审查 F-02): 纯数字/标点/空白/零宽的写入(钱数 0-999、零宽空格等)
            // 根本不需要译文, 旧版却把它们全记成 [TMP MISS]: 一次运行 1,002 条 uniqMiss 里
            // 1,001 条是 HUD 钱数, 真正的英文漏译被埋掉, "0 miss" 发布门槛事实上不可判定。
            // 现在这类串单独计数 (missNoise), 不再进 miss 统计与 DIAG。
            if (Core.IsNoiseOnly(key)) { TmpMissNoise++; return; }
            if (SeenMiss.Count < 5000 && SeenMiss.Add(key)) D("[TMP MISS] \"" + Trunc(key) + "\" @" + CompPath(__instance));
            TmpMiss++;
        }

        // v1.3.33 结构侧: 整句包色判定与回包逻辑搬进 Core.cs(零 Unity 依赖, 可在游戏外自检)。
        // 这里只保留 DIAG 记录 —— 每次回包写一行 [WRAP], 实机据此确认包裹有没有被吃掉。
        private static int WrapLogged;
        private static string RewrapColor(string orig, string zh)
        {
            string open = Core.WholeWrapOpen(orig);
            if (open != null && Core.WholeWrapOpen(zh) == null && WrapLogged < 50)
            { WrapLogged++; D("[WRAP] 回包 " + open + " : " + Trunc(zh)); }
            return Core.RewrapColor(orig, zh);
        }
        // v1.3.33 结构侧: 数字模板 / 恋人弹窗 / 道具复合弹窗 / 道具名取值的纯逻辑
        // 都搬进 Core.cs(词典由调用方传入, Core 不持有任何全局状态)。
        // 这里四个薄壳只做两件 Plugin 才有的事: 喂插件持有的词典, 写 DIAG。
        private static string TryNumTemplate(string key) { return Core.TryNumTemplate(key, Disp); }
        private static string TryRomance(string key) { return Core.TryRomance(key, Disp); }
        private static string LookupItemName(string key) { return Core.LookupItemName(key, Disp, ItemNames); }
        private static string TryItemGet(string s)
        {
            List<string> miss;
            string r = Core.TryItemGet(s, Disp, ItemNames, out miss);
            for (int i = 0; i < miss.Count; i++) D("[ITEM_NAME MISS] " + Trunc(miss[i]));
            return r;
        }
        // v1.3.30 (F2): 判定当前 TMP 文本位是不是"道具名"位, 以及是否为 HUD 的"名字 xN"小提示。
        // 道具名位与角色名牌拿到的是同一串英文(Lebkuchen), 显示词典按英文归一只能二选一;
        // 二者真正的差别只在组件路径上, 所以按路径判上下文。路径口径来自实机 DIAG 的 @组件路径:
        //   商店列表  NormalItems/…/ShopItemView(Clone)/Name
        //   背包列表  NormalItems|FoodItems|KeyItems/…/ItemView(Clone)/Name
        //   道具详情  …/ItemDetail/…/Name
        //   HUD 提示  HUD/ItemStatus/ItemGetSmall/Name   ("名字 xN", 见 Core.ItemQtyRe)
        // 先做廉价前置过滤(叶子名), 只有候选位才去拼路径 —— CompPath 有字符串开销,
        // 每次文本写入都无谓调用会白白摊薄帧率。
        private static bool ItemNameCtx(object inst, string key, out bool hudToast)
        {
            hudToast = false;
            var comp = inst as UnityEngine.Component;
            if (comp == null) return false;
            string leaf;
            try { leaf = comp.name; } catch { return false; }
            if (leaf != "Name" && leaf != "ItemName" && leaf != "Title") return false;
            string path = CompPath(inst);
            if (path.IndexOf("ItemGetSmall", StringComparison.Ordinal) >= 0) { hudToast = true; return true; }
            if (path.IndexOf("ShopItemView(Clone)", StringComparison.Ordinal) >= 0) return true;
            if (path.IndexOf("ItemView(Clone)", StringComparison.Ordinal) >= 0) return true;
            if (path.IndexOf("ItemDetail", StringComparison.Ordinal) >= 0) return true;
