        private void Awake()
        {
            Log = Logger;
            // v1.3.31: DIAG 必须在载入译文表之前打开 —— 否则 LoadTable 期间的 [DEGRADE]
            // 与载入日志都会丢掉(旧版顺序是 LoadTable→OpenDiag, 译文表出问题在 DIAG 里看不到)。
            OpenDiag();
            LoadTable();
