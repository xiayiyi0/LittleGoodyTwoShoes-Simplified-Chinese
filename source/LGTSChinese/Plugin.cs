                            && string.Equals(cps[pi].Name, "overrideLanguage", StringComparison.OrdinalIgnoreCase))
                        { hasOverrideLanguage = true; break; }
                    if (hasOverrideLanguage) { GetTranslationMethod = candidate; break; }
                }
            }
            D("I2 语言门: CurrentLanguageCode 属性=" + (I2LangCodeProp != null ? "已取得" : "缺失(默认按英语)")
              + " 英语资源键取词=" + (GetTranslationMethod != null ? "已取得" : "缺失"));
            var post = new HarmonyMethod(typeof(Plugin).GetMethod("GetTranslation_Postfix",
                BindingFlags.Static | BindingFlags.NonPublic));
            var postTry = new HarmonyMethod(typeof(Plugin).GetMethod("TryGetTranslation_Postfix",
                BindingFlags.Static | BindingFlags.NonPublic));
            int n = 0;
            foreach (var m in lm.GetMethods(BindingFlags.Public | BindingFlags.Static))
            {
                var ps = m.GetParameters();
                // GetTranslation / GetTermTranslation(string, ...) -> string
                if (m.ReturnType == typeof(string) && (m.Name == "GetTranslation" || m.Name == "GetTermTranslation")
                    && ps.Length >= 1 && ps[0].ParameterType == typeof(string))
                {
                    try { harmony.Patch(m, postfix: post); n++; Log.LogInfo("已挂钩 " + m); }
                    catch (Exception e) { Log.LogWarning("挂钩失败 " + m + ": " + e.Message); }
                }
                // TryGetTranslation(string Term, out string Translation, ...) -> bool
                // 【关键】过场/道具/HUD 等系统多用此法取词, 只挂 GetTranslation 会漏。
                else if (m.Name == "TryGetTranslation" && m.ReturnType == typeof(bool)
                    && ps.Length >= 2 && ps[0].ParameterType == typeof(string)
                    && ps[1].ParameterType.IsByRef && ps[1].ParameterType.GetElementType() == typeof(string))
                {
                    try { harmony.Patch(m, postfix: postTry); n++; Log.LogInfo("已挂钩 " + m); }
                    catch (Exception e) { Log.LogWarning("挂钩失败 " + m + ": " + e.Message); }
                }
            }
            // TermData.GetTranslation(int, ...) 实例法 —— 直接读 TermData 的路径(部分过场)。
            Type td = AccessTools.TypeByName("I2.Loc.TermData");
            if (td != null)
            {
                TermField = td.GetField("Term");
                var postTd = new HarmonyMethod(typeof(Plugin).GetMethod("TermData_Postfix",
                    BindingFlags.Static | BindingFlags.NonPublic));
                foreach (var m in td.GetMethods(BindingFlags.Public | BindingFlags.Instance))
                {
                    if (m.Name == "GetTranslation" && m.ReturnType == typeof(string))
                    {
                        try { harmony.Patch(m, postfix: postTd); n++; Log.LogInfo("已挂钩 TermData." + m); }
                        catch (Exception e) { Log.LogWarning("挂钩失败 TermData." + m + ": " + e.Message); }
                    }
                }
            }
            if (n == 0) Log.LogError("未挂上任何取词方法");
            else Log.LogInfo("共挂钩 " + n + " 个取词方法");
        }

        // ---- v1.3.16 选择器护栏: I2 "按名选资源"型 Localize 目标不得注入中文 ----
        // I2 的对象选择目标会把 mainTranslation 当作【子物体名/资源名查找键】用
        // (child.name==text / FindTranslatedObject<T>(mainTranslation)), 而非显示文本。若我们的取词后钩把英文键
        // 改成中文, 查找必然失配 → 选错/选空物体, 可能表现为谜题机关失灵、UI 图片消失或过场卡死。
        // Localize.OnLocalize 内的调用顺序(反编译 Assembly-CSharp): 先 GetTranslation(FinalTerm)
        // 取词(此时 CurrentLocalizeComponent 尚未赋值), 之后才 DoLocalize —— 因此无法在取词后钩里
        // 反查调用方类型。护栏做法: 在 OnLocalize 外层包一对 prefix/finalizer, prefix 判断本组件的
        // mLocalizeTarget 是否为上述"对象选择器", 是则置抑制标志; finalizer 恢复(异常也恢复,
        // 支持嵌套 save/restore)。三个取词后钩(GT/TRY/TD)在标志置位时一律不注入。
        // 文本型目标(TextMeshPro_Label/_UGUI/TextMesh)不置标志, 照常翻译。
        [ThreadStatic] internal static bool SuppressTermInject;
        private static HashSet<string> ObjSelectorTypeNames = new HashSet<string>(StringComparer.Ordinal)
        {
            "I2.Loc.LocalizeTarget_UnityStandard_Child",
            "I2.Loc.LocalizeTarget_UnityStandard_Prefab",
            "I2.Loc.LocalizeTarget_UnityStandard_MeshRenderer",
            "I2.Loc.LocalizeTarget_UnityStandard_SpriteRenderer",
            "I2.Loc.LocalizeTarget_UnityStandard_AudioSource",
            "I2.Loc.LocalizeTarget_UnityUI_Image",
            "I2.Loc.LocalizeTarget_UnityUI_RawImage",
        };
        private static FieldInfo LocTargetField;   // I2.Loc.Localize.mLocalizeTarget
        private static int GuardHits;
        private void PatchLocalizeGuard(Harmony harmony)
        {
            Type loc = AccessTools.TypeByName("I2.Loc.Localize");
            if (loc == null) { Log.LogWarning("护栏: 未找到 I2.Loc.Localize"); D("[GUARD] Localize 类缺失, 护栏未挂"); return; }
            LocTargetField = loc.GetField("mLocalizeTarget", BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.Instance);
            if (LocTargetField == null) { Log.LogWarning("护栏: 未找到 mLocalizeTarget 字段"); D("[GUARD] mLocalizeTarget 字段缺失, 护栏未挂"); return; }
            var m = AccessTools.Method(loc, "OnLocalize", new Type[] { typeof(bool) })
                    ?? AccessTools.Method(loc, "OnLocalize");
            if (m == null) { Log.LogWarning("护栏: 未找到 Localize.OnLocalize"); D("[GUARD] OnLocalize 方法缺失, 护栏未挂"); return; }
            var pre = new HarmonyMethod(typeof(Plugin).GetMethod("OnLocalize_Prefix", BindingFlags.Static | BindingFlags.NonPublic));
            pre.priority = Priority.First;
            var fin = new HarmonyMethod(typeof(Plugin).GetMethod("OnLocalize_Finalizer", BindingFlags.Static | BindingFlags.NonPublic));
            try { harmony.Patch(m, prefix: pre, finalizer: fin); Log.LogInfo("已挂钩 Localize.OnLocalize 选择器护栏"); D("[GUARD] OnLocalize 护栏已挂"); }
            catch (Exception e) { Log.LogWarning("护栏挂钩失败: " + e.Message); D("[GUARD] 挂钩失败: " + e.Message); }
        }

        // __state 保存进入前的抑制标志值以支持嵌套; 本组件目标为对象选择器则置位。
        // v1.3.17 (C6): 窄窗口加固 —— Localize.OnLocalize 内 GetTranslation(行154) 先于
        // FindTarget(行164) 执行, 而 FindTarget 正是 mLocalizeTarget 从 null 解析出来的
        // 地方(Awake 曾解析过, 但 target 失效重建/首次场景加载可能仍为 null)。此窗口里
        // 前缀查不到 target 类型, 护栏静默失效。权衡: null 时一律抑制(宁可该次显示英文,
        // 不可把中文注进"按名选资源"的查找键导致选错物体/机关失灵)。若本组件实为文本
        // 目标, 行164 FindTarget 会把 mLocalizeTarget 解析好, 下次 OnLocalize 即恢复正常
        // 翻译 —— 错杀代价(一帧英文、可自愈)远小于漏杀代价(谜题失灵/图片消失)。
        private static void OnLocalize_Prefix(object __instance, out bool __state)
        {
            __state = SuppressTermInject;
            try
            {
                object tgt = LocTargetField != null ? LocTargetField.GetValue(__instance) : null;
                if (tgt == null)
                {
                    SuppressTermInject = true;
                    if (GuardHits < 50) { GuardHits++; D("[GUARD] mLocalizeTarget==null, 保守抑制 (窄窗口)"); }
                    return;
                }
                if (ObjSelectorTypeNames.Contains(tgt.GetType().FullName))
                {
                    SuppressTermInject = true;
                    if (GuardHits < 50) { GuardHits++; D("[GUARD] 抑制注入 target=" + tgt.GetType().Name); }
                }
            }
            catch { /* 护栏自身异常绝不可影响游戏本地化 */ }
        }
        private static void OnLocalize_Finalizer(bool __state)
        {
            SuppressTermInject = __state;
        }

        private static void LogTerm(string term, bool hit, string src)
        {
            if (Logged.Count < 400 && Logged.Add(src + ":" + term))
                D("[" + src + "] " + (hit ? "HIT  " : "MISS ") + "term=" + term + " refkey=" + Core.RefKey(term));
            if ((Hits + Miss) % 500 == 0)
                D("[HEARTBEAT] GT/TRY/TD hits=" + Hits + " miss=" + Miss
                  + " | DoLoc hit=" + DoLocHit + " miss=" + DoLocMiss
                  + " | TMP seen=" + TmpSeen + " fixed=" + TmpFixed);
        }

        // GetTranslation / GetTermTranslation 的后置: __0 = 词条键(按位置取)
        // v1.3.6 加固: 仅当原查询成功(返回非空)时才替换译文, 不改变"词条不存在"的语义,
        // 避免影响任何以取词成败做分支的调用方(兼容性审查 P14)。
        // v1.3.7 (B2): 非英语言不注入。
        private static void GetTranslation_Postfix(ref string __result, string __0)
        {
            try { GetTranslation_PostfixCore(ref __result, __0); }
            catch (Exception e) { if (HookErr < 20) { HookErr++; D("[HOOK ERR] GT: " + e.Message); } }
        }
        private static void GetTranslation_PostfixCore(ref string __result, string __0)
        {
            string Term = __0;
            if (string.IsNullOrEmpty(Term)) return;
            if (string.IsNullOrEmpty(__result)) { Miss++; LogTerm(Term, false, "GT"); return; }
            if (!I2LangIsEnglish()) return;
            if (SuppressTermInject) return;   // v1.3.16: 对象选择器取词, 键不可译
            string zh;
            bool hit = Zh.TryGetValue(Core.RefKey(Term), out zh) && !string.IsNullOrEmpty(zh);
            if (hit) { __result = zh; Hits++; } else Miss++;
            LogTerm(Term, hit, "GT");
        }

        // TryGetTranslation(string Term, out string Translation) -> bool
        // v1.3.6 加固: 不再强制 __result=true; 原查询失败时保持失败。
        // v1.3.7 (B2): 非英语言不注入。
        private static void TryGetTranslation_Postfix(string __0, ref string __1, ref bool __result)
        {
            try { TryGetTranslation_PostfixCore(__0, ref __1, ref __result); }
            catch (Exception e) { if (HookErr < 20) { HookErr++; D("[HOOK ERR] TRY: " + e.Message); } }
        }
        private static void TryGetTranslation_PostfixCore(string __0, ref string __1, ref bool __result)
        {
            string Term = __0;
            if (string.IsNullOrEmpty(Term) || !__result) return;
            if (!I2LangIsEnglish()) return;
            if (SuppressTermInject) return;   // v1.3.16: 对象选择器取词, 键不可译
            string zh;
            if (Zh.TryGetValue(Core.RefKey(Term), out zh) && !string.IsNullOrEmpty(zh))
            { __1 = zh; Hits++; LogTerm(Term, true, "TRY"); }
            else { Miss++; LogTerm(Term, false, "TRY"); }
        }

        // TermData.GetTranslation 实例法: 从 __instance.Term 取键
        // v1.3.6 加固: 原返回为空(该语言无译文)时不注入, 保持原语义。
        // v1.3.7 (B2): 非英语言不注入。
        private static void TermData_Postfix(object __instance, ref string __result)
        {
            try { TermData_PostfixCore(__instance, ref __result); }
            catch (Exception e) { if (HookErr < 20) { HookErr++; D("[HOOK ERR] TD: " + e.Message); } }
        }
        private static void TermData_PostfixCore(object __instance, ref string __result)
        {
            if (__instance == null || TermField == null) return;
            if (string.IsNullOrEmpty(__result)) return;
            if (!I2LangIsEnglish()) return;
            if (SuppressTermInject) return;   // v1.3.16: 对象选择器取词, 键不可译
            string Term = TermField.GetValue(__instance) as string;
            if (string.IsNullOrEmpty(Term)) return;
            string zh;
            if (Zh.TryGetValue(Core.RefKey(Term), out zh) && !string.IsNullOrEmpty(zh))
            { __result = zh; Hits++; LogTerm(Term, true, "TD"); }
            else { Miss++; LogTerm(Term, false, "TD"); }
        }

