# -*- coding: utf-8 -*-
"""把 stage 发布树打成玩家分发的 zip, 并重算 SHA256SUMS.txt。

    python tools/repack.py --stage dist/stage_v1324 --version 1.3.24
    python tools/repack.py --stage ... --version ... --expect-entries 71

范围 = BepInEx 全树 + 顶层文件白名单。刻意不含 source/ 与 SHA256SUMS.txt
(SHA256SUMS 覆盖 zip 本体, 打包后才算, 不能进 zip)。
条目数必须等于 --expect-entries, 数量变化必须先从 changelog 解释清楚再改预期值。
"""
import argparse
import hashlib
import os
import sys
import zipfile

TOP = [".doorstop_version", ".gitignore", "LICENSE", "LICENSE-NOTICE.txt", "README.md",
       "arialuni_sdf_u2019", "changelog.txt", "doorstop_config.ini", "winhttp.dll",
       "安装说明_README.txt"]

SUMS = [
    ("BepInEx/plugins/LGTSChinese/LGTSChinese.dll", "dll"),
    ("BepInEx/plugins/LGTSChinese/translation/lgts_display.json", "json"),
    ("BepInEx/plugins/LGTSChinese/translation/lgts_zh_by_refkey.json", "json"),
    ("BepInEx/plugins/LGTSChinese/translation/lgts_item_names.json", "json"),
    ("BepInEx/Translation/zh/Text/_AutoGeneratedTranslations.txt", "text"),
    ("BepInEx/Translation/zh/Text/UI_System.txt", "text"),
]

# v1.3.27 (审计 S2): 顶层发布文件此前不在 SHA256SUMS 里 —— 重打包后只要保留
# "vX.Y.Z (" 字样, changelog/安装说明正文可任意改写而验收全绿。现全部纳入。
SUMS_TOP = ["LICENSE", "LICENSE-NOTICE.txt", "README.md", "arialuni_sdf_u2019",
            "changelog.txt", "doorstop_config.ini", "winhttp.dll", "安装说明_README.txt"]


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", required=True, help="stage 发布树目录")
    ap.add_argument("--version", required=True, help="例如 1.3.24")
    ap.add_argument("--expect-entries", type=int, default=71)
    args = ap.parse_args()

    stage = os.path.abspath(args.stage)
    zip_name = "LGTS-SimplifiedChinese-v%s.zip" % args.version
    zip_path = os.path.join(stage, zip_name)

    count = 0
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for root, dirs, files in os.walk(os.path.join(stage, "BepInEx")):
            dirs[:] = [d for d in dirs if d != "__pycache__"]
            for f in files:
                full = os.path.join(root, f)
                z.write(full, os.path.relpath(full, stage).replace("\\", "/"))
                count += 1
        for f in TOP:
            full = os.path.join(stage, f)
            if not os.path.exists(full):
                sys.exit("顶层文件缺失: " + f)
            z.write(full, f)
            count += 1

    print("打包 %d 个文件 (预期 %d)" % (count, args.expect_entries))
    if count != args.expect_entries:
        sys.exit("条目数不符, 请先确认变化并更新 --expect-entries")

    entries = [(zip_path, zip_name)]
    for rel, _ in SUMS:
        entries.append((os.path.join(stage, rel.replace("/", os.sep)), rel))
    for rel in SUMS_TOP:
        entries.append((os.path.join(stage, rel), rel))
    lines = ["%s %s" % (sha256(p), rel) for p, rel in entries]
    with open(os.path.join(stage, "SHA256SUMS.txt"), "wb") as f:
        f.write("\n".join(lines).encode("utf-8") + b"\n")

    print("SHA256SUMS.txt (%d 行):" % len(lines))
    for l in lines:
        print("  " + l)
    print("\nzip: %s" % zip_name)
    print("大小: %d B" % os.path.getsize(zip_path))
    print("sha256: %s" % sha256(zip_path))


if __name__ == "__main__":
    sys.exit(main())
