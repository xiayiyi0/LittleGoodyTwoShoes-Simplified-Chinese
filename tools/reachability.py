# -*- coding: utf-8 -*-
"""可达性清单: 给定一批记录键, 逐行回答"发布产物里到底有没有一条能把它送上屏的路径"。

    python tools/reachability.py --rows 待核实机_登记.md --csv docs/译本.csv --out tools/acceptance/可达性.md
    python tools/reachability.py --all     --csv docs/译本.csv          # 全表普查
    python tools/reachability.py --keys DLG_3_2_HFY_01_011,XUAT_04584

为什么需要这个工具
    译本里 28,248 行, 但游戏取词只有两条路, 谁走哪条路由"记录键前缀"决定:
      A 直取: GridlyLocal.GetStringData(tab, recordID) -> by_refkey[recordID]
              recordID 就是译本记录键。只有非 XUAT_ 行才可能走这条
              (XUAT_ 行是 2026-10-25 从 AT/display 遗留层收编的, 没有游戏 RefKey,
               apply_translation.py 按设计不把它们写进 by_refkey)。
      B 兜底: 英文串 -> Norm() -> display[键]   (插件 TMP/I2 钩子)
      C 兜底: 英文串 -> _AutoGeneratedTranslations.txt / UI_System.txt (XUnity 层)
      D 道具名: Norm(英文) -> item_names[键]     (仅道具名位)

    "键在词典里"不等于"能上屏": 同一英文有多个译文候选时 display 只能留一条,
    其余行的措辞永远不会出现; 也可能某行的英文压根不在键集里。这两种情况都得点名,
    否则译者会一直排某几行的队, 而那几行没有任何一条路。

判定口径
    直取             A 命中且值相等 —— 这句由 Gridly 直接换成中文, 不看 B/C。
    兜底-本行        A 无路(或 XUAT), B 命中且显示值就是本行译文。
    兜底-本行/AT     B 无路, C 命中且值相等。
    兜底-道具名/本行 B/C 无路, D 命中。
    兜底-他人        键在 B/C, 但显示值是**另一行**的译文 —— 本行措辞永不上屏。
    无路             四条路都没有 —— 这行改了也不会有人看得见。

注意: 本工具判的是"结构可达", 不是"实机已经加载过"。要证明某一行真的被游戏请求过,
只能靠 DIAG (G 组会断言零 MISS) 或加键表探针后的实机跑; 结构可达是必要条件,
不满足必要条件时才可以直接下结论 —— 无路。
"""
import argparse
import csv
import json
import os
import re
import sys
from collections import defaultdict

TAG_RE = re.compile(r"<[/#a-zA-Z][^>]*>")
WS_RE = re.compile(r"\s+")
PUNCT = set("、，。！？：；（）【】「」『』—…·“”‘’!?()[].,:;-\u3000 ")
NB = chr(92) + "n"          # 字面反斜杠 + n


def norm(s):
    """与 Core.Norm / apply_translation.norm 一致: 剥标签(含 <br>, 不换空格) -> 折空白 -> trim。"""
    return WS_RE.sub(" ", TAG_RE.sub("", s or "")).strip()


def depunct(s):
    return "".join(ch for ch in s if ch not in PUNCT)


def clean_zh(s):
    s = re.sub(r"</?(?:wave|shake|incr)\b[^>]*>", "", s or "").strip()
    return s.replace("\u2022", "\u30FB")


def load_kv_text(path):
    """读 XUnity 词典: 每行 键=值, 值里的换行是字面 \\n。返回 (原始键字典, 折叠键字典)。"""
    raw, folded = {}, {}
    if not os.path.exists(path):
        return raw, folded
    for ln in open(path, encoding="utf-8", newline=""):
        ln = ln.rstrip("\r\n")
        if not ln or ln.startswith("#") or "=" not in ln:
            continue
        k, v = ln.split("=", 1)
        raw.setdefault(k, v)
        folded.setdefault(norm(k.replace(NB, " ")), v)
    return raw, folded


def pick_winner(cands, shown):
    """cands: [(记录键, 译文, 英文)] —— 找出与显示值去标点后相同的那条(可能并列)。"""
    if not shown:
        return []
    dp = depunct(shown)
    return [c[0] for c in cands if depunct(c[1]) == dp]


def extract_keys(path, after=None):
    """从 markdown 表格/清单里按出现顺序抽出记录键 (反引号内或独立词)。

    after: 只解析「首次出现该子串」之后的行 —— 登记表常有多张表(已结清/待判),
           不设边界会把别的表的键一并带进来。
    """
    out, seen = [], set()
    pat = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
    armed = after is None
    for ln in open(path, encoding="utf-8-sig"):
        if not armed:
            if after in ln:
                armed = True
            continue
        for tok in re.split(r"[`\s|｜／]+", ln):
            tok = tok.strip().strip("*")
            if tok and pat.match(tok) and tok[0].isupper():
                if tok not in seen:
                    seen.add(tok)
                    out.append(tok)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--csv", required=True)
    ap.add_argument("--rows", default=None, help="记录键清单来源 (md/txt), 只判这些行")
    ap.add_argument("--after", default=None, help="配合 --rows: 只解析含该子串的行之后的内容")
    ap.add_argument("--keys", default=None, help="逗号分隔的记录键")
    ap.add_argument("--all", action="store_true", help="全表普查")
    ap.add_argument("--tran", default=None, help="词典目录, 默认取仓库内自带")
    ap.add_argument("--out", default=None, help="输出 markdown 报告 (utf-8)")
    ap.add_argument("--at-baseline", action="append", default=None,
                    help="旧 AT 备份 (可多次); 加一列『该英文键在旧词典里是否已有』作为键龄证据")
    ap.add_argument("--min-len", type=int, default=12, help="无路/遮蔽 的行按英文长度过滤短噪声")
    args = ap.parse_args()

    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    tran = args.tran or os.path.join(repo, "BepInEx", "plugins", "LGTSChinese", "translation")
    # tran = <root>/BepInEx/plugins/LGTSChinese/translation -> <root>/BepInEx/Translation/zh/Text
    atdir = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(tran))),
                         "Translation", "zh", "Text")

    rows = list(csv.DictReader(open(args.csv, encoding="utf-8-sig")))
    has_rev = "修订译文" in rows[0].keys()
    eff = lambda r: clean_zh(((r.get("修订译文") or "").strip() or r["中文译文"]) if has_rev else r["中文译文"])

    bykey = {}
    cands_by_norm = defaultdict(list)          # Norm(英文) 字面键 -> [(记录键, 译文, 英文)]
    cands_by_fold = defaultdict(list)          # Norm(英文折 \n-> 空格) -> 同上
    for r in rows:
        k, zh, en = r["记录键"], eff(r), r["英文原文"].strip()
        bykey[k] = (zh, en)
        if zh and en:
            cands_by_norm[norm(en)].append((k, zh, en))
            cands_by_fold[norm(en.replace(NB, " "))].append((k, zh, en))

    rk = json.load(open(os.path.join(tran, "lgts_zh_by_refkey.json"), encoding="utf-8"))
    disp = json.load(open(os.path.join(tran, "lgts_display.json"), encoding="utf-8"))
    itn = json.load(open(os.path.join(tran, "lgts_item_names.json"), encoding="utf-8"))
    at_raw, at_fold = load_kv_text(os.path.join(atdir, "_AutoGeneratedTranslations.txt"))
    ui_raw, ui_fold = load_kv_text(os.path.join(atdir, "UI_System.txt"))
    baselines = []
    for bp in (args.at_baseline or []):
        raw, _fold = load_kv_text(bp)
        baselines.append((os.path.basename(bp), set(raw)))
    print("loaded: by_refkey=%d display=%d item_names=%d AT=%d UI=%d"
          % (len(rk), len(disp), len(itn), len(at_raw), len(ui_raw)))

    if args.keys:
        targets = [k.strip() for k in args.keys.split(",") if k.strip()]
    elif args.rows:
        targets = extract_keys(args.rows, args.after)
    elif args.all:
        targets = [r["记录键"] for r in rows]
    else:
        sys.exit("需要 --rows / --keys / --all 之一")

    def probe(k):
        got = bykey.get(k)
        if got is None:
            return None
        zh, en = got
        rec = {"key": k, "zh": zh, "en": en, "xuat": k.startswith("XUAT_")}
        nk = norm(en)

        # A 直取
        a = rk.get(k)
        rec["A"] = None if a is None else ("==" if depunct(a) == depunct(zh) else "!=")
        rec["A_val"] = a

        # B 兜底 —— 两个字面键都要查:
        #   nk  = Norm(英文原文) 原样, 英文列里的换行是字面 \n 时键里也带 \n;
        #   nf  = 把字面 \n 折成空格后的键。游戏运行时给的串里换行是真换行,
        #        插件 Norm() 会把它折成空格, 所以**真正上屏命中的是 nf**。
        #  2026-11-13 rebuild_at 踩的就是这个坑(AT:1), 这里把两种键都列出来。
        b = disp.get(nk)
        rec["B"] = b
        rec["B_key"] = nk if nk in disp else None
        rec["B_win"] = pick_winner(cands_by_norm.get(nk, []), b) if b else []
        nf = norm(en.replace(NB, " "))
        bf = disp.get(nf)
        rec["Bf"] = bf
        rec["Bf_key"] = nf if nf in disp else None
        rec["Bf_win"] = pick_winner(cands_by_fold.get(nf, []), bf) if bf else []

        # C 兜底 (AT / UI_System)
        variants = [en, en.replace("\r\n", "\n"), en.replace("\n", NB)]
        ck = cv = None
        for v in variants:
            if v in at_raw:
                ck, cv = v, at_raw[v]
                break
        if ck is None and nf in at_fold:
            ck, cv = nf, at_fold[nf]
        if ck is None:
            for v in (en, en.replace("\n", NB), nk):
                if v in ui_raw:
                    ck, cv = v, ui_raw[v]
                    break
            if ck is None and nf in ui_fold:
                ck, cv = nf, ui_fold[nf]
        rec["C"] = cv
        rec["C_same"] = bool(cv) and depunct(cv.replace(NB, "\n")) == depunct(zh)
        rec["C_key"] = ck

        # D 道具名
        rec["D"] = itn.get(nk) or itn.get(nf)

        # 旧 AT 键龄: 该英文串在我们的旧词典里是否已经存在(仅作历史证据, 不参与判定)
        rec["old"] = [n for n, ks in baselines
                      if any(v in ks for v in (en, en.replace("\n", NB), nf))]

        # 判定 (A > B字面 > B折键 > C > D); "本行"= 该层显示的就是本行译文
        if rec["A"] == "==":
            rec["verdict"] = "直取"
        elif b is not None and k in rec["B_win"]:
            rec["verdict"] = "兜底-本行"
        elif b is not None and rec["B_win"]:
            rec["verdict"] = "兜底-他人"
        elif b is not None:
            rec["verdict"] = "兜底-遗留"
        elif bf is not None and k in rec["Bf_win"]:
            rec["verdict"] = "兜底-本行/折键"
        elif bf is not None and rec["Bf_win"]:
            rec["verdict"] = "兜底-他人/折键"
        elif rec["C"] and rec["C_same"]:
            rec["verdict"] = "兜底-本行/AT"
        elif rec["C"]:
            rec["verdict"] = "兜底-他人/AT"
        elif rec["D"] and depunct(rec["D"]) == depunct(zh):
            rec["verdict"] = "兜底-道具名/本行"
        else:
            rec["verdict"] = "无路"
        return rec

    recs = [r for r in (probe(k) for k in targets) if r]
    missing = [k for k in targets if bykey.get(k) is None]
    tally = defaultdict(int)
    for r in recs:
        tally[r["verdict"]] += 1
    print("targets=%d found=%d missing_in_csv=%d" % (len(targets), len(recs), len(missing)))
    print("verdicts: " + ", ".join("%s=%d" % (k, v) for k, v in sorted(tally.items())))

    lines = []
    hdr = "| 记录键 | 英文(截断) | 译文(截断) | A 直取 | B 显示(字面键) | B 显示(折\\n键) | C AT | D 道具名 | 判定 |"
    sep = "|---|---|---|---|---|---|---|---|---|"
    if baselines:
        hdr += " 旧AT键龄 |"
        sep += "---|"
    lines.append(hdr)
    lines.append(sep)
    tag = {"直取": "**直取**", "兜底-本行": "兜底·本行", "兜底-本行/折键": "兜底·折键",
           "兜底-本行/AT": "兜底·AT", "兜底-他人": "**遮蔽**", "兜底-他人/折键": "**遮蔽·折键**",
           "兜底-他人/AT": "**遮蔽·AT**", "兜底-遗留": "兜底·遗留值",
           "兜底-道具名/本行": "兜底·道具", "无路": "**无路**"}

    def cell_b(val, win, key):
        if val is None:
            return "键缺"
        if key in win:
            return "= 本行" + ("（并列 %d 行）" % len(win) if len(win) > 1 else "")
        if win:
            return "≠ " + "、".join("`%s`" % w for w in win[:2])
        return "≠ 遗留值"

    for r in recs:
        a = "-" if r["A"] is None else ("命中" if r["A"] == "==" else "值异")
        b = cell_b(r["B"], r["B_win"], r["key"])
        bf = cell_b(r["Bf"], r["Bf_win"], r["key"])
        c = "-" if not r["C"] else ("= 本行" if r["C_same"] else "≠ 他文")
        d = "-" if r["D"] is None else "命中"
        en = r["en"].replace("\n", "⏎").replace("|", "｜")
        zh = r["zh"].replace("\n", "⏎").replace("|", "｜")
        parts = ["`%s`" % r["key"], en[:46], zh[:26], a, b, bf, c, d,
                 tag.get(r["verdict"], r["verdict"])]
        if baselines:
            # 旧词典里是否已有该英文键: 多份时逐份标注(只留后缀名, 省略 _AutoGeneratedTranslations.txt)
            parts.append(" ".join("`%s`=%s" % (n.split(".bak")[-1] or n, "有" if n in r["old"] else "-")
                                  for n, _ in baselines) if len(baselines) > 1 else
                         ("有" if r["old"] else "-"))
        lines.append("| " + " | ".join(parts) + " |")

    if args.out:
        os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
        with open(args.out, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines) + "\n")
        print("report -> %s (%d rows)" % (args.out, len(recs)))

    if args.all:
        dead = [r for r in recs if r["verdict"] in ("无路", "兜底-他人", "兜底-他人/折键",
                                                    "兜底-他人/AT", "兜底-遗留")]
        dead_len = [r for r in dead if len(norm(r["en"])) >= args.min_len]
        print("dead/shadowed=%d (英文>=%d 字符: %d)" % (len(dead), args.min_len, len(dead_len)))
        for r in dead_len[:25]:
            print("  %-22s %s" % (r["key"], r["verdict"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())