# v1.3.27 (审计 S2): 顶层发布文件纳入 SHA256SUMS 与 stage↔zip 比对。
SHIPPED_TOP = ["LICENSE", "LICENSE-NOTICE.txt", "README.md", "arialuni_sdf_u2019",
               "changelog.txt", "doorstop_config.ini", "winhttp.dll", "安装说明_README.txt"]
EXPECT_SUMS = 1 + len(FILES) + len(SHIPPED_TOP)

# 2026-11-04 (外部审查 F-03): 检查项总数的自断言。缺 --csv/--live 时会有检查项
# 直接不执行且不留 SKIP, 汇总行照样只报 PASS — 只有"应跑 == 实跑"才能发现。
# 改检查项时必须同步改这个数。
# v1.3.31: 39 → 42 (新增 G 组 3 项运行时诊断; 不带 --diag 时基线自动 -3)。
EXPECTED_CHECKS = 42


def main():
    # v1.3.27 (S3): 先把 stdout 的编码错误策略改成转义, 避免任何一处 print 撞字库外字符。
    try:
        sys.stdout.reconfigure(errors="backslashreplace")
    except Exception:
        pass
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", required=True)
    ap.add_argument("--version", required=True)
    ap.add_argument("--live", default=None, help="游戏根目录 (可选)")
    ap.add_argument("--csv", default=None, help="译本 CSV (可选)")
    ap.add_argument("--diag", default=None,
                    help="实机 DIAG.txt (可选; 给出则检查运行时诊断: 无 [TMP MISS] / 无未登记 [DEGRADE])")
    ap.add_argument("--zip", default=None, help="默认取发布树内唯一 zip")
    ap.add_argument("--expect-entries", type=int, default=71)
    ap.add_argument("--expect-refkey", type=int, default=21189)
    ap.add_argument("--expect-display", type=int, default=25293)
    ap.add_argument("--expect-item", type=int, default=79)
    ap.add_argument("--expect-at", type=int, default=24700)
    ap.add_argument("--expect-ui", type=int, default=536)
    args = ap.parse_args()

    stage = os.path.abspath(args.stage)
    ver = args.version
    zip_path = args.zip
    if not zip_path:
        cands = [p for p in glob.glob(os.path.join(stage, "*.zip"))]
        if len(cands) != 1:
            sys.exit("发布树内应恰好有一个 zip, 实际 %d 个" % len(cands))
        zip_path = cands[0]

    print("---------- A 包结构 ----------")
    with zipfile.ZipFile(zip_path) as z:
        names = [x for x in z.namelist() if not x.endswith("/")]
        check("zip 条目 %d" % args.expect_entries, len(names) == args.expect_entries, str(len(names)))
        check("zip 无 source/ 与 .git",
              not any(x == ".git" or x.startswith(".git/") or x.startswith("source/") for x in names))
        check("zip 无 SHA256SUMS (自身不可入包)", "SHA256SUMS.txt" not in names)
        check("zip 含字体 arialuni_sdf_u2019", "arialuni_sdf_u2019" in names)
        zsha = {rel: hashlib.sha256(z.read(rel)).hexdigest() for rel in FILES}
        dll = z.read(FILES[0])
        check("DLL 含版本串 %s" % ver,
              ver.encode("ascii") in dll and (ver + ".0").encode("utf-16-le") in dll)
        chg = z.read("changelog.txt").decode("utf-8")
        check("changelog 有 v%s 段" % ver, ("v%s (" % ver) in chg)
        readme = z.read("安装说明_README.txt").decode("utf-8")
        check("安装说明正文为 v%s" % ver, ver in readme)
        # v1.3.27 (S2): 顶层文件也要与发布树逐字节一致, 否则"改 stage 不重打包"无人发现。
        top_bad = [f for f in SHIPPED_TOP
                   if f not in names
                   or hashlib.sha256(z.read(f)).hexdigest()
                   != sha256(os.path.join(stage, f))]
        check("stage==zip 顶层发布文件 (%d)" % len(SHIPPED_TOP), not top_bad, str(top_bad))

    sums_path = os.path.join(stage, "SHA256SUMS.txt")
    sums = [l for l in rd(sums_path).splitlines() if l.strip()]
    check("SHA256SUMS %d 行" % EXPECT_SUMS, len(sums) == EXPECT_SUMS, str(len(sums)))
    ok = True
    covered = set()
    for line in sums:
        h, rel = line.split(" ", 1)
        covered.add(rel)
        p = os.path.join(stage, rel.replace("/", os.sep))
        if not os.path.exists(p) or sha256(p) != h:
            ok = False
    check("SHA256SUMS 自举一致", ok)
    # 覆盖性: 发布树里每个要发出去的文件都必须在 SUMS 里, 不能只覆盖 6 个词典/DLL。
    need = set(FILES) | set(SHIPPED_TOP)
    check("SHA256SUMS 覆盖全部发布文件", need <= covered, str(sorted(need - covered)))

    print("\n---------- B 三树一致 ----------")
    if args.live:
        for rel in FILES:
            live = sha256(os.path.join(args.live, rel.replace("/", os.sep)))
            stg = sha256(os.path.join(stage, rel.replace("/", os.sep)))
            check("live==stage==zip " + os.path.basename(rel),
                  live == stg == zsha[rel], live[:12])
    else:
        for rel in FILES:
            check("stage==zip " + os.path.basename(rel),
                  sha256(os.path.join(stage, rel.replace("/", os.sep))) == zsha[rel])
        check("live 比对", True, "未提供 --live, 跳过", skipped=True)

    print("\n---------- C 词典口径 ----------")
    base = args.live or stage
    disp = json.load(open(os.path.join(base, r"BepInEx\plugins\LGTSChinese\translation\lgts_display.json"), encoding="utf-8"))
    rkey = json.load(open(os.path.join(base, r"BepInEx\plugins\LGTSChinese\translation\lgts_zh_by_refkey.json"), encoding="utf-8"))
    itn = json.load(open(os.path.join(base, r"BepInEx\plugins\LGTSChinese\translation\lgts_item_names.json"), encoding="utf-8"))
    at = read_at(os.path.join(base, r"BepInEx\Translation\zh\Text\_AutoGeneratedTranslations.txt"))
    ui = read_ui(os.path.join(base, r"BepInEx\Translation\zh\Text\UI_System.txt"))
    check("by_refkey %d" % args.expect_refkey, len(rkey) == args.expect_refkey, str(len(rkey)))
    check("display %d" % args.expect_display, len(disp) == args.expect_display, str(len(disp)))
    check("item_names %d" % args.expect_item, len(itn) == args.expect_item, str(len(itn)))
    check("AT %d" % args.expect_at, len(at) == args.expect_at, str(len(at)))
    check("UI_System %d (已跳过 # 注释)" % args.expect_ui, len(ui) == args.expect_ui, str(len(ui)))

    if args.csv:
        rows = list(csv.DictReader(open(args.csv, encoding="utf-8-sig")))
        has_rev = bool(rows) and "修订译文" in rows[0]
        BAD_TAG_RE = re.compile(r"</?(?:wave|shake|incr)\b[^>]*>")
        eff = lambda r: BAD_TAG_RE.sub("", ((r.get("修订译文") or "").strip() or r["中文译文"]) if has_rev else r["中文译文"]).strip()
        # XUAT_ 行是从词典遗留层收编来的, 没有游戏 RefKey, 不参与 by_refkey 比对。
        mism = [r["记录键"] for r in rows
                if not r["记录键"].startswith("XUAT_") and eff(r) and rkey.get(r["记录键"]) != eff(r)]
        check("by_refkey 与译本逐条相等", not mism, str(len(mism)))
        xk = [k for k in rkey if k.startswith("XUAT_")]
        check("by_refkey 无 XUAT 收编键", not xk, str(len(xk)))

        # v1.3.26 起遗留层已收编: 三本词典的每一个键都必须能在译本里找到英文原文。
        def _nk(s):
            return re.sub(r"\s+", " ", re.sub(r"<[/#a-zA-Z][^>]*>", "", s or "")).strip()
        covered = set()
        for r in rows:
            e = r.get("英文原文") or ""
            if e:
                covered.add(_nk(e))
                covered.add(_nk(e.replace("\n", " ")))
        # 运行时逐行字幕层(tools/runtime_lines.txt): 时间轴逐句 cue 与多行记录的
        # 单行键, 译本 CSV 里没有对应英文原文(整条才有一条记录), 但它们是实机上屏串,
        # 由 apply_translation.py 一并写入 display, 这里认作已覆盖。
        rt_lines = {}
        _rtp = os.path.join(os.path.dirname(os.path.abspath(__file__)), "runtime_lines.txt")
        if os.path.exists(_rtp):
            for _ln in open(_rtp, encoding="utf-8"):
                if not _ln.strip() or _ln.startswith("#"):
                    continue
                _p = _ln.rstrip("\r\n").split("\t")
                if len(_p) < 2:
                    continue
                _rk, _rv = _nk(_p[0]), _p[1].replace("\\n", "\n").strip()
                if _rk and _rv:
                    rt_lines[_rk] = _rv
        covered |= set(rt_lines)
        uncov = {}
        for name, m in (("display", disp), ("AT", at), ("item", itn)):
            n = sum(1 for k in m if _nk(k) not in covered)
            if n:
                uncov[name] = n
        check("译本覆盖 display/AT/item 全部键", not uncov, str(uncov))

        # 值级校验: 三层每个键的值必须等于译本中同一 Norm(英文) 的取值。
        # 这是 2026-10-26 审计 E1 指出的盲区 —— 只查"键在不在"的话, 把译文整段
        # 换成不相干内容也能 PASS。同形异义走 NAME_OVERRIDE 白名单; 换行与 <br>
        # 视为等价; AT 里的字面 \n 先反转义。
        NAME_OVERRIDE = {"Lebkuchen": "斯佩尔特"}

        def _canon(s):
            s = (s or "").replace("\\n", "\n").replace("<br>", "\n")
            return re.sub(r"\s+", " ", s).strip()

        vcand = {}
        for r in rows:
            e = r.get("英文原文") or ""
            zh = BAD_TAG_RE.sub("", r.get("中文译文") or "").strip()
            if e.strip() and zh:
                vcand.setdefault(_nk(e), set()).add(_canon(zh))
                vcand.setdefault(_nk(e.replace("\n", " ")), set()).add(_canon(zh))
        for _rk, _rv in rt_lines.items():      # 运行时逐行字幕层: 期望值取自本层
            vcand.setdefault(_rk, set()).add(_canon(_rv))
        vbad = {}
        for name, m in (("display", disp), ("AT", at), ("item", itn)):
            for k, v in m.items():
                if k in NAME_OVERRIDE:
                    continue
                cs = vcand.get(_nk(k))
                if cs is None:
                    continue          # 缺键由上面的覆盖率检查负责
                if _canon(v) not in cs:
                    vbad[name] = vbad.get(name, 0) + 1
        check("三层值均与译本一致", not vbad, str(vbad))

        # 2026-11-04 (外部审查 F-04 的实证): 同一归一键有多条不同译文时, 上屏取哪一条由
        # tools/pick_overrides.txt 钉死, 两者必须双向相等:
        #   漏钉  -> 下次 --scratch 重建按 CSV 行序取候选第一条, 悄悄改掉上屏文案
        #            (v1.3.21 "Lebkuchen 名牌被写成姜饼" 就是这个机制);
        #   陈旧  -> 碰撞已被统一, override 行会掩盖规则变化; 记录键若改名还会 KeyError。
        _po = {}
        _pop = os.path.join(os.path.dirname(os.path.abspath(__file__)), "pick_overrides.txt")
        if os.path.exists(_pop):
            for _ln in open(_pop, encoding="utf-8"):
                if _ln.startswith("#") or "\t" not in _ln:
                    continue
                _pk, _pr = _ln.rstrip("\r\n").split("\t", 1)
                _po[_pk] = _pr
        _nm = {}
        for r in rows:
            _zh = eff(r)
            _en = r.get("英文原文") or ""
            if not _zh or not _en.strip():
                continue
            _nm.setdefault(_nk(_en.strip()), set()).add(_zh)
        _coll = {k for k, v in _nm.items() if len(v) > 1}
        _unpinned = sorted(_coll - set(_po))
        _stale = sorted(set(_po) - _coll)
        check("同归一键多译文=override 表 一致",
              not _unpinned and not _stale,
              "未钉 %d %s / 陈旧 %d %s" % (len(_unpinned), _unpinned[:2],
                                            len(_stale), _stale[:2]))

        # 缺图标的空格洞: 原文本里的 <sprite> 在键里被剥掉, 值里若只留两个空格,
        # 上屏就是一个空档 (2026-10-26 审计 S1)。只查行内, 不碰 \n\n 空行。
        HOLE = re.compile(r"[^\s　] {2,}[^\s　]|[^\s　] {1,}[，。！？；：、]")
        hb = {}
        for name, m in (("display", disp), ("refkey", rkey), ("item", itn), ("AT", at)):
            for v in m.values():
                if isinstance(v, str) and any(HOLE.search(seg) for seg in v.split("\n")):
                    hb[name] = hb.get(name, 0) + 1
        check("四层无缺图标空格洞", not hb, str(hb))

        # 键集清单必须与产物一致 —— 两者一致才说明"清空词典后能原样重建"。
        # 清单在 tools/keys_display.txt / tools/keys_at.txt。
        for fn, m, label in (("keys_display.txt", disp, "display"),
                             ("keys_at.txt", at, "AT"),
                             ("keys_refkey.txt", rkey, "refkey"),
                             ("keys_item.txt", itn, "item")):
            kp = os.path.join(os.path.dirname(os.path.abspath(__file__)), fn)
            if not os.path.exists(kp):
                check("键集清单 " + fn, True, "缺失, 跳过", skipped=True)
                continue
            ks = {ln.rstrip("\r\n") for ln in open(kp, encoding="utf-8") if ln.strip()}
            if m is disp:
                ks |= set(rt_lines)      # 运行时逐行字幕层的键另由 runtime_lines.txt 提供
            check("键集与 %s 一致" % fn, ks == set(m),
                  "清单 %d / 产物 %d" % (len(ks), len(m)))

        print("\n---------- D 标点 / 标签 ----------")
        zh = re.compile("[\\u4e00-\\u9fff]")
        bad = {}
        for name, m in (("display", disp), ("refkey", rkey), ("item", itn), ("AT", at), ("UI", ui)):
            for v in m.values():
                if not isinstance(v, str) or not zh.search(v):
                    continue
                for tok in ("......", "--", "!", "?"):
                    if tok in v:
                        bad[name + ":" + tok] = bad.get(name + ":" + tok, 0) + 1
        check("五层无 ...... -- ! ? 残留", not bad, str(bad))

        # 游戏 TMP 不识别这三个标签, 上屏会变成字面量 (v1.3.8 实机确认, v1.3.21 重建时回归过)。
        BADTAG = re.compile(r"</?(?:wave|shake|incr)\b")
        stale = {}
        for name, m in (("display", disp), ("refkey", rkey), ("item", itn), ("AT", at), ("UI", ui)):
            for v in m.values():
                if isinstance(v, str) and BADTAG.search(v):
                    stale[name] = stale.get(name, 0) + 1
        check("五层无 wave/shake/incr 字面标签", not stale, str(stale))

        # display / AT 里有几千条英文串不在译本中, 旧译文会把错叫名写成真名。
        # 规则见 apply_translation.NAME_GUARD。
        # mercy 小写是"仁慈", 只有大写 Mercy 才是人名。
        NAME_GUARD = [("Rosmarine", "萝森玛琳", re.I), ("Rozenmarine", "萝丝玛琳", re.I),
                      ("Mercy", "梅西", 0), ("Macy", "默茜", 0)]
        ng = {}
        for name, m in (("display", disp), ("AT", at)):
            for k, v in m.items():
                if not isinstance(v, str):
                    continue
                for en, wrong, flags in NAME_GUARD:
                    if wrong in v and re.search(r"\b" + en + r"\b", k, flags):
                        ng[name + ":" + en] = ng.get(name + ":" + en, 0) + 1
        check("display/AT 错叫名未串名", not ng, str(ng))

        # 半角括号/冒号/分号只该出现在遗留层, 已由工具规范化。UI_System 是
        # display.json 缺失才走的退回路径, 不在本检查范围。
        HALF = re.compile(r"\([^()]*[一-鿿][^()]*\)"
                          r"|(?<=[一-鿿])[:;]|[:;](?=[一-鿿])")
        hp = {}
        for name, m in (("display", disp), ("refkey", rkey), ("item", itn), ("AT", at)):
            for v in m.values():
                if isinstance(v, str) and HALF.search(v):
                    hp[name] = hp.get(name, 0) + 1
        check("四层无半角括号/冒号/分号", not hp, str(hp))

        tagbad = 0
        for v in list(rkey.values()) + list(disp.values()):
            o, c = {}, {}
            for t in re.findall(r"<([a-zA-Z]+)(?=[\s=>/])", v):
                o[t] = o.get(t, 0) + 1
            for t in re.findall(r"</([a-zA-Z]+)>", v):
                c[t] = c.get(t, 0) + 1
            for t in ("sprite", "br"):
                o.pop(t, None)
            if o != c:
                tagbad += 1
        check("富文本标签配对", tagbad == 0, str(tagbad))

        print("\n---------- E 内容抽查 ----------")
        sample = [r for r in rows if eff(r) and r["记录键"] in rkey]
        random.seed(len(rows))
        picked = random.sample(sample, min(5, len(sample)))
        check("随机 5 条与译本一致",
              all(rkey[r["记录键"]] == eff(r) for r in picked),
              str([r["记录键"] for r in picked]))
    else:
        check("译本逐条比对", True, "未提供 --csv, 跳过", skipped=True)

    print("\n---------- F 字形 ----------")
    try:
        import UnityPy  # noqa: F401
    except ImportError:
        check("字形覆盖", True, "未安装 UnityPy, 跳过", skipped=True)
    else:
        import numpy  # noqa: F401
        D = None
        env = UnityPy.load(os.path.join(base, "arialuni_sdf_u2019"))
        for o in env.objects:
            if o.type.name == "MonoBehaviour":
                d = o.read_typetree()
                if isinstance(d, dict) and "m_CharacterTable" in d:
                    D = d
        if D is None:
            check("字形覆盖", False, "字体内未找到 m_CharacterTable")
        else:
            glyphs = {c["m_Unicode"] for c in D["m_CharacterTable"]}
            missing = {}
            corpora = {"display": disp, "refkey": rkey, "item": itn, "AT": at, "UI": ui}
            for name, m in corpora.items():
                for v in m.values():
                    if not isinstance(v, str):
                        continue
                    for ch in v:
                        if ch in "\r\n\t":
                            continue
                        if ord(ch) not in glyphs:
                            missing[name + ":" + ch] = missing.get(name + ":" + ch, 0) + 1
            check("全部字符有字形", not missing,
                  str(dict(list(missing.items())[:5])))

    # ---------- G 运行时诊断 (v1.3.31) ----------
    # 外部审查 F-01/F-02 的正解: 覆盖率断言只证"产物 ⊆ 译本", 证明不了"游戏面 ⊆ 产物"。
    # 唯一的运行时证据是 DIAG.txt, 所以把它纳入机器验收: 任何一条 [TMP MISS] 都代表
    # 有英文串没查到译文; 任何未登记的 [DEGRADE] 都代表插件降级运行。
    if args.diag:
        try:
            dtext = open(args.diag, encoding="utf-8", errors="replace").read().splitlines()
            derr = None
        except Exception as e:
            dtext, derr = None, e
        if derr is not None:
            check("DIAG 可读", False, str(derr))
            check("DIAG 无 [TMP MISS]", False, "DIAG 不可读")
            check("DIAG 无未登记 [DEGRADE]", False, "DIAG 不可读")
        else:
            check("DIAG 行数 > 100", len(dtext) > 100, str(len(dtext)))
            miss = [l for l in dtext if "[TMP MISS]" in l]
            check("DIAG 无 [TMP MISS]", not miss,
                  "前 3 条: %s" % [m[:70] for m in miss[:3]])
            # 已知良性降级: 本机 TMP 全局 fallback 注入失败(Unity/TMP 版本差异),
            # 字形由 arialuni 与 UGUI 系统字体通道承担, 玩家侧无可见影响。
            DEGRADE_OK = ("TMP 全局 fallback",)
            deg = [l for l in dtext if "[DEGRADE]" in l]
            bad = [l for l in deg if not any(k in l for k in DEGRADE_OK)]
            check("DIAG 无未登记 [DEGRADE]", not bad,
                  "未登记 %d 条 %s / 良性 %d 条"
                  % (len(bad), [b[:70] for b in bad[:3]], len(deg) - len(bad)))

    # 2026-11-04 (外部审查 F-03): 验收器自身也要被验收。
    # 省略 --live 时 "live 比对" 这一项会以 SKIP 记录 (比全参数多 1 条), 基线相应 +1;
    # 省略 --diag 时 G 组 3 项整体不执行, 基线相应 -3。
    n_ran = len(RESULTS)
    expected = EXPECTED_CHECKS + (0 if args.live else 1) - (0 if args.diag else 3)
    if n_ran != expected:
        check("应跑检查项 %d (实跑 %d)" % (expected, n_ran), False,
              "差 %d 项未执行, 多半是缺 --csv (译本相关检查整块不跑); 发布门槛必须带全参数重跑"
              % abs(expected - n_ran))
    failed = [r for r in RESULTS if r[1] == "FAIL"]
    skipped = [r for r in RESULTS if r[1] == "SKIP"]
    _out("\n=== %d PASS / %d FAIL / %d SKIP ==="
         % (len(RESULTS) - len(failed) - len(skipped), len(failed), len(skipped)))
    _out("退出码 0=全绿 / 1=有 FAIL / 2=有 SKIP 或检查未跑全 (未完成的验收不算通过)")
    if failed:
        return 1
    if skipped or n_ran != expected:
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
