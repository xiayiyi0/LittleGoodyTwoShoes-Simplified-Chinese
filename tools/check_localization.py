# -*- coding: utf-8 -*-
"""本地化交付自检（不进发布包，纯离线）。

四道门：
  G1 请求可满足   —— 游戏可能请求的每个串，在「TMP 层(规则+display)」或「XUAT 层(AT)」能取到值
  G2 无英文回退   —— 取到的值不得是原文本身，除非该记录在译本里被显式标为免译
  G3 标签/换行一致 —— 原文有的富文本标签与换行，译文不许少（例外见 tools/check_allow.txt）
  G4 键未归并     —— 不同记录被归一成同一个键时，译文必须相同，或被 pick_overrides 钉住

用法：
  python tools/check_localization.py                     # 查仓库自带的词典
  python tools/check_localization.py --live "D:\\game"    # 查实机安装树
  python tools/check_localization.py --stage dist/stage_v1332
退出码：0 = 四道门全过；1 = 有 FAIL。
"""
import argparse
import csv
import json
import os
import re
import sys
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)

# ---------- 与 Plugin.cs 对齐的归一化与规则 ----------
TAG = re.compile(r"</?[a-zA-Z#][^>]*>")
WS = re.compile(r"\s+")
CJK = re.compile(r"[\u3400-\u9fff\uf900-\ufaff]")


def norm(s):
    s = TAG.sub("", s or "")
    s = s.replace("<br>", "")
    return WS.sub(" ", s).strip()


SaveTimeRe = re.compile(r"^DATE\s+(.+?)\s+TIME\s+(.+)$")
QtySuffixRe = re.compile(r"^[xX]\s*(\d{1,4})$")
RoundRe = re.compile(r"^ROUND\s+(\d+)$", re.I)
RetryCostRe = re.compile(r"^\((\d+)\s*[Tt]\)$")
NumRe = re.compile(r"\d+")
DayTimeRe = re.compile(
    r"^(Sunday|Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sun\.|Mon\.|Tue\.|Wed\.|Thu\.|Fri\.|Sat\.)"
    r"\s*\.?\s*(Morning|Afternoon|Evening|Night|Dawn|Dusk|Noon|Daytime|Witching Hour|Witch\. Hour)$", re.I)
RomanceRe = re.compile(
    r"^(Rozenmarine|Freya|Lebkuchen)('s)?\s+(Heart Piece Ac?quired!|Everlasting Love!|Strong Bond)$", re.I)
AcquiredRe = re.compile(r"^Acquired\s+(\d+)$")

DayMap = {"sunday": "周日", "sun.": "周日", "monday": "周一", "mon.": "周一", "tuesday": "周二",
          "tue.": "周二", "wednesday": "周三", "wed.": "周三", "thursday": "周四", "thu.": "周四",
          "friday": "周五", "fri.": "周五", "saturday": "周六", "sat.": "周六"}
TimeMap = {"morning": "上午", "afternoon": "下午", "evening": "傍晚", "night": "夜晚", "dawn": "黎明",
           "dusk": "黄昏", "noon": "正午", "daytime": "白天", "witching hour": "巫魅时分",
           "witch. hour": "巫魅时分"}


class Layers(object):
    def __init__(self, base):
        tran = os.path.join(base, "BepInEx", "plugins", "LGTSChinese", "translation")
        text = os.path.join(base, "BepInEx", "Translation", "zh", "Text")
        self.display = self._json(os.path.join(tran, "lgts_display.json"))
        self.refkey = self._json(os.path.join(tran, "lgts_zh_by_refkey.json"))
        self.item = self._json(os.path.join(tran, "lgts_item_names.json"))
        self.at = self._at(os.path.join(text, "_AutoGeneratedTranslations.txt"))

    @staticmethod
    def _json(p):
        if not os.path.exists(p):
            return {}
        with open(p, encoding="utf-8-sig") as f:
            return json.load(f)

    @staticmethod
    def _at(p):
        d = {}
        if not os.path.exists(p):
            return d
        with open(p, encoding="utf-8-sig") as f:
            for line in f:
                line = line.rstrip("\r\n")
                if not line or line[0] == "#" or "=" not in line:
                    continue
                k, _, v = line.partition("=")
                d[k] = v
        return d

    # ---- 模拟插件判定链 ----
    def resolve(self, raw):
        """返回 (来源, 值)；来源 ∈ rule/dict/numtpl/romance/at/None。"""
        s = raw
        if CJK.search(s):
            return ("cjk", s)
        key = norm(s)
        if not key:
            return ("empty", None)

        m = SaveTimeRe.match(key)
        if m:
            # 与 Plugin.cs 一致：日期/时间分行，避免中文在「时/间」中间被字符换行切断
            return ("rule", "日期 " + m.group(1).strip() + "\n时间 " + m.group(2).strip())
        m = QtySuffixRe.match(key)
        if m:
            return ("rule", "×" + m.group(1))
        m = RoundRe.match(key)
        if m:
            return ("rule", "第 " + m.group(1) + " 回合")
        m = RetryCostRe.match(key)
        if m:
            return ("rule", "（" + m.group(1) + "T）")
        m = DayTimeRe.match(key)
        if m and DayMap.get(m.group(1).lower()) and TimeMap.get(m.group(2).lower()):
            sep = "\n" if "\n" in key else " "
            return ("rule", DayMap[m.group(1).lower()] + sep + TimeMap[m.group(2).lower()])
        m = AcquiredRe.match(key)
        if m:
            return ("rule", "获得了 " + m.group(1) + " 个")

        v = self.display.get(key)
        if v:
            return ("dict", v)

        # 数字模板
        if len(key) <= 300 and re.search(r"\d", key) and re.search(r"[A-Za-z]", key):
            nums = []

            def sub(mm):
                nums.append(mm.group(0))
                return "{%d}" % (len(nums) - 1)
            tpl = NumRe.sub(sub, key)
            if len(nums) <= 4:
                zh = self.display.get(tpl)
                if zh:
                    for i, n in enumerate(nums):
                        zh = zh.replace("{%d}" % i, n)
                    return ("numtpl", zh)

        # 恋人弹窗
        m = RomanceRe.match(key)
        if m:
            name = m.group(1)
            zh_name = self.display.get(name, name)
            tail = m.group(3)
            zh_tail = self.display.get(tail)
            if not zh_tail:
                if tail.lower().startswith("heart piece"):
                    zh_tail = "获得爱心碎片!"
                elif tail.lower().startswith("everlasting"):
                    zh_tail = "永恒之爱!"
                else:
                    zh_tail = "深厚羁绊"
            return ("romance", "<b>" + zh_name + ("的" if m.group(2) else "") + "</b>\n" + zh_tail)

        # XUAT 层（AT）：原样键 → 归一键（AT 的键可能是含字面 \n 的「英文原文」形态）
        for k in (s, s.strip(), key):
            v = self.at.get(k)
            if v:
                return ("at", v.replace("\\n", "\n"))
        return (None, None)


ALLOW_PATH = os.path.join(HERE, "check_allow.txt")


def load_allow():
    tag_allow, nl_allow = {}, {}
    if os.path.exists(ALLOW_PATH):
        for line in open(ALLOW_PATH, encoding="utf-8-sig"):
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split(None, 1)
            if len(parts) != 2:
                continue
            kind, key = parts[0].upper(), parts[1].strip()
            (tag_allow if kind == "TAG" else nl_allow)[key] = True
    return tag_allow, nl_allow


def tag_kinds(s):
    out = Counter()
    for m in TAG.finditer(s or ""):
        t = m.group(0).lower()
        if t.startswith("<sprite"):
            out["sprite"] += 1
        elif t.startswith("<color"):
            out["color"] += 1
        elif t.startswith("</color"):
            out["color"] += 1
        elif t.startswith("<b>"):
            out["b"] += 1
        elif t.startswith("</b>"):
            out["b"] += 1
        elif t.startswith("<i>"):
            out["i"] += 1
        elif t.startswith("</i>"):
            out["i"] += 1
        elif t.startswith("<size"):
            out["size"] += 1
        elif t.startswith("</size"):
            out["size"] += 1
        elif t.startswith("<br"):
            out["br"] += 1
    return out


def nl_count(s):
    return (s or "").count("\n") + len(re.findall(r"<br\s*/?>", s or "", re.I))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--live", default=None, help="游戏根目录（查实机安装树）")
    ap.add_argument("--stage", default=None, help="发布树目录")
    ap.add_argument("--csv", default=None, help="译本 CSV（默认 docs/ 下唯一一份）")
    ap.add_argument("--show", type=int, default=15, help="每个门最多打印多少条失败明细")
    args = ap.parse_args()

    base = args.live or args.stage or REPO
    csvp = args.csv
    if not csvp:
        docs = os.path.join(REPO, "docs")
        csvs = [f for f in os.listdir(docs) if f.endswith(".csv")]
        if not csvs:
            sys.exit("找不到译本 CSV")
        csvp = os.path.join(docs, csvs[0])

    L = Layers(base)
    rows = list(csv.DictReader(open(csvp, encoding="utf-8-sig", newline="")))
    tag_allow, nl_allow = load_allow()

    fails = 0

    def report(ok, title, detail=""):
        nonlocal fails
        print(("PASS " if ok else "FAIL ") + title + (("  | " + detail) if detail else ""))
        if not ok:
            fails += 1

    print("========== 本地化交付自检 ==========")
    print("词典根: %s" % base)
    print("译本  : %s" % csvp)
    print("层规模: display %d / by_refkey %d / item %d / AT %d"
          % (len(L.display), len(L.refkey), len(L.item), len(L.at)))
    print("")

    # ---------------- G1 请求可满足 ----------------
    print("---------- G1 请求可满足 ----------")
    req_status_ok = {"已译", "指针行免译", "指针行免译·目标缺失"}
    misses, src_count = [], Counter()
    req_total = 0
    for r in rows:
        en = r["英文原文"]
        if not en.strip() or r["状态"] not in req_status_ok:
            continue
        req_total += 1
        src, val = L.resolve(en)
        src_count[src or "MISS"] += 1
        if not val:
            misses.append((r["记录键"], r["状态"], en))
    report(not misses, "G1.1 译本每一行都能取到值",
           "%d / %d 行命中，来源分布 %s" % (req_total - len(misses), req_total, dict(src_count)))
    for k, st, en in misses[:args.show]:
        print("    - %s [%s] %r" % (k, st, en[:60]))
    if len(misses) > args.show:
        print("    ... 另有 %d 条" % (len(misses) - args.show))

    rt_bad = []
    rt_path = os.path.join(HERE, "runtime_lines.txt")
    rt_lines = []
    if os.path.exists(rt_path):
        for line in open(rt_path, encoding="utf-8-sig"):
            line = line.rstrip("\r\n")
            if not line or line.lstrip().startswith("#"):
                continue
            k = line.split("\t")[0]
            rt_lines.append(k)
            if not L.display.get(k):
                rt_bad.append(k)
    report(not rt_bad, "G1.2 runtime_lines 每条都已并入 display", "%d 条，缺 %d" % (len(rt_lines), len(rt_bad)))
    for k in rt_bad[:args.show]:
        print("    - %r" % k)

    rk_bad = [r["记录键"] for r in rows
              if r["状态"] == "已译" and r["中文译文"].strip()
              and not r["记录键"].startswith("XUAT_") and r["记录键"] not in L.refkey]
    report(not rk_bad, "G1.3 非 XUAT 的已译行都进了 by_refkey(I2 路径)", "缺 %d" % len(rk_bad))
    for k in rk_bad[:args.show]:
        print("    - %s" % k)

    item_bad = [k for k, v in L.item.items() if not v]
    report(not item_bad, "G1.4 item_names 无空值", "%d 键，空 %d" % (len(L.item), len(item_bad)))

    # 合成请求：实机出现过 / 代码会拼出来的形态
    synth = ["x1", "x23", "x9999", "ROUND 1", "ROUND 12", "Round 3", "(5T)", "(12t)",
             "DATE 2026/11/4 TIME 02:07:37", "DATE 2020/1/1 TIME 00:00:00",
             "Mon. Evening", "Monday . Afternoon", "Sun. Morning", "Sunday . Dusk",
             "Witching Hour", "Witch. Hour", "Acquired 3", "Unlock for 30", "Unlock for 2",
             "Collected fireflies: 7", "Rozenmarine's Heart Piece Acquired!",
             "Freya Everlasting Love!", "Lebkuchen Strong Bond"]
    synth_bad = []
    for s in synth:
        src, val = L.resolve(s)
        if not val:
            synth_bad.append(s)
    report(not synth_bad, "G1.5 规则/模板/拼串形态都能取到值",
           "%d 条合成请求，缺 %d" % (len(synth), len(synth_bad)))
    for s in synth_bad[:args.show]:
        print("    - %r" % s)

    # 存档位日期时间：必须两行，且「时间」不能在被字符换行切断（实机 2026-11-04 出过）
    save_dates = ["2026/11/4", "2026/10/21", "2026/12/31", "2025/9/2", "2026/1/1"]
    layout_bad = []
    for d in save_dates:
        req = "DATE %s TIME 00:44:55" % d
        src, val = L.resolve(req)
        if not val:
            layout_bad.append((req, "无译文"))
            continue
        lines = val.split("\n")
        if len(lines) != 2:
            layout_bad.append((req, "行数=%d 应为 2：%r" % (len(lines), val)))
        elif "时间" not in val:
            layout_bad.append((req, "「时间」被切断：%r" % val))
        elif max(len(x) for x in lines) > 20:
            layout_bad.append((req, "行过长 %d 字：%r" % (max(len(x) for x in lines), val)))
    report(not layout_bad, "G1.6 存档位「日期/时间」两行且不被切断",
           "%d 个日期样本，问题 %d" % (len(save_dates), len(layout_bad)))
    for req, why in layout_bad[:args.show]:
        print("    - %s ｜ %s" % (req, why))

    # 发布 DLL 与规则实现一致：存档时间串必须是「\n时间 」，否则校验器测的与玩家跑的就不是一回事
    dllp = os.path.join(base, "BepInEx", "plugins", "LGTSChinese", "LGTSChinese.dll")
    if os.path.exists(dllp):
        blob = open(dllp, "rb").read()
        ok2 = blob.count((chr(10) + "时间 ").encode("utf-16-le")) >= 1
        oldstyle = blob.count(" 时间 ".encode("utf-16-le"))
        report(ok2 and oldstyle == 0, "G1.7 发布 DLL 用的是「日期/时间」分行实现",
               "含 \\n时间 =%d，旧形态 ' 时间 ' =%d" % (blob.count((chr(10) + "时间 ").encode("utf-16-le")), oldstyle))
    else:
        print("SKIP G1.7 发布 DLL 未提供（只验数据）")

    # ---------------- G2 无英文回退 ----------------
    print("")
    print("---------- G2 无英文回退 ----------")
    MENEI = ("免译", "人名", "名单", "图片路径", "测试", "指针行")
    leaked = []
    for r in rows:
        if r["状态"] != "已译" or not r["英文原文"].strip() or not r["中文译文"].strip():
            continue
        if r["中文译文"].strip() != r["英文原文"].strip():
            continue
        note = r["审查备注"]
        if any(m in note for m in MENEI):
            continue
        leaked.append((r["记录键"], r["分类"], note[:30]))
    report(not leaked, "G2.1 译文==原文的行都已标注免译理由", "未标注 %d" % len(leaked))
    for k, cat, note in leaked[:args.show]:
        print("    - %s [%s] 备注=%r" % (k, cat, note))

    empty_zh = [r["记录键"] for r in rows if r["状态"] == "已译" and not r["中文译文"].strip()]
    report(not empty_zh, "G2.2 已译行没有空译文", "空 %d" % len(empty_zh))

    # ---------------- G3 标签/换行一致 ----------------
    print("")
    print("---------- G3 标签/换行与原文一致 ----------")
    tag_lost, nl_lost, unbalanced = [], [], []
    for r in rows:
        en, zh = r["英文原文"], r["中文译文"]
        if r["状态"] not in req_status_ok or not en.strip() or not zh.strip():
            continue
        ce, cz = tag_kinds(en), tag_kinds(zh)
        lost = [k for k in ("sprite", "color", "size", "i", "b", "br") if cz.get(k, 0) < ce.get(k, 0)]
        if lost and r["记录键"] not in tag_allow:
            tag_lost.append((r["记录键"], lost, en[:40]))
        if nl_count(en) >= 1 and nl_count(zh) == 0 and r["记录键"] not in nl_allow:
            nl_lost.append(r["记录键"])
        for k in ("color", "b", "i", "size"):
            if cz.get(k, 0) % 2 != 0:
                unbalanced.append((r["记录键"], k))
                break
    report(not tag_lost, "G3.1 原文的富文本标签没有丢", "丢 %d 行（白名单 %d）" % (len(tag_lost), len(tag_allow)))
    for k, lost, en in tag_lost[:args.show]:
        print("    - %s 丢了 %s ｜ %r" % (k, lost, en))
    report(not nl_lost, "G3.2 原文有换行的，译文不许压成一行", "违反 %d 行（白名单 %d）" % (len(nl_lost), len(nl_allow)))
    for k in nl_lost[:args.show]:
        print("    - %s" % k)
    report(not unbalanced, "G3.3 译文里标签开闭配对", "不配对 %d 行" % len(unbalanced))
    for k, tag in unbalanced[:args.show]:
        print("    - %s 的 %s" % (k, tag))

    # ---------------- G4 键未归并 ----------------
    print("")
    print("---------- G4 键未归并 ----------")
    ov_path = os.path.join(HERE, "pick_overrides.txt")
    ov = {}
    if os.path.exists(ov_path):
        for line in open(ov_path, encoding="utf-8-sig"):
            line = line.rstrip("\r\n")
            if not line or line.lstrip().startswith("#"):
                continue
            k, _, rec = line.partition("\t")
            ov[k] = rec
    groups = defaultdict(list)
    for r in rows:
        en, zh = r["英文原文"], r["中文译文"]
        if not en.strip() or not zh.strip():
            continue
        groups[norm(en)].append((r["记录键"], zh))
    merged = []
    for key, lst in groups.items():
        if len(lst) < 2:
            continue
        vals = set(v for _, v in lst)
        if len(vals) < 2:
            continue
        if key not in ov:
            merged.append((key, [k for k, _ in lst]))
    report(not merged, "G4.1 一归一键多译文都已用 pick_overrides 钉住", "未钉 %d 组" % len(merged))
    for key, ks in merged[:args.show]:
        print("    - %r ← %s" % (key[:40], ks[:4]))

    dangling = []
    stale = []
    for key, rec in ov.items():
        lst = groups.get(key, [])
        if not lst:
            dangling.append((key, rec))
            continue
        if len(set(v for _, v in lst)) < 2:
            stale.append(key)
        elif rec not in [k for k, _ in lst]:
            dangling.append((key, rec))
    report(not dangling, "G4.2 pick_overrides 指向的记录都存在且键真有碰撞", "悬空 %d" % len(dangling))
    for key, rec in dangling[:args.show]:
        print("    - %r -> %s" % (key[:40], rec))
    report(not stale, "G4.3 pick_overrides 没有陈旧条目", "陈旧 %d" % len(stale))
    for key in stale[:args.show]:
        print("    - %r" % key[:40])

    print("")
    print("========== %s ==========" % ("全部通过" if fails == 0 else "%d 项 FAIL" % fails))
    return 0 if fails == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
